import fs from 'node:fs';
import test from 'node:test';
import assert from 'node:assert/strict';
import {scan,readInventory} from './原H52静态审计.mjs';
const files=readInventory();
const h=files.find(x=>x.file.endsWith('/f05-7-frozen-h52-revalidation.yml'));
test('8份原文件完整读到并且SHA校验',()=>assert.equal(files.length,8));
test('历史H52确切52个Job',()=>assert.equal(h.job_count,52));
test('总66个Job',()=>assert.equal(files.reduce((s,x)=>s+x.job_count,0),66));
test('64个PG16服务声明',()=>assert.equal(files.reduce((s,x)=>s+x.pg16_services,0),64));
test('110次potential artifact上传声明',()=>assert.equal(files.reduce((s,x)=>s+x.upload_actions,0),110));
test('总3520理论最大Runner分钟',()=>assert.equal(files.reduce((s,x)=>s+x.max_runner_minutes,0),3520));
test('4个Job使用360分钟默认timeout',()=>assert.equal(files.reduce((s,x)=>s+x.default_timeout,0),4));
test('H52 511380B',()=>assert.equal(h.bytes,511380));
test('H52没有矩阵扩张',()=>assert.deepEqual(h.matrix_jobs,[]));
test('负例：缺失jobs禁止冒充通过',()=>assert.throws(()=>scan('name: empty\n')));
test('负例：重复Job键禁止冒充唯一',()=>assert.throws(()=>scan('jobs:\n  x:\n    runs-on: ubuntu-latest\n  x:\n    runs-on: ubuntu-latest\n')));
test('负例：空jobs禁止冒充完整图',()=>assert.throws(()=>scan('jobs:\n')));
test('负例：Job自动默认360不得默认为40',()=>assert.equal(scan('jobs:\n  x:\n    runs-on: ubuntu-latest\n').max_runner_minutes,360));
test('负例：显式更长Job预算准确发现',()=>assert.equal(scan('jobs:\n  x:\n    timeout-minutes: 41\n').max_runner_minutes,41));
