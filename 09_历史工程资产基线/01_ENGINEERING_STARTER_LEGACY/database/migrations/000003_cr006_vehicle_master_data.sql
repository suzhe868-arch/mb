  model_id BIGINT NOT NULL REFERENCES vehicle_models(model_id) ON DELETE RESTRICT,
  source_platform TEXT NOT NULL,
  upstream_model_id TEXT NOT NULL,
  field_name TEXT NOT NULL,
  current_value JSONB,
  incoming_value JSONB,
  conflict_status TEXT NOT NULL DEFAULT 'open' CHECK(conflict_status IN ('open','resolved_keep_local','resolved_accept_upstream')),
  first_seen_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  last_seen_at TIMESTAMPTZ NOT NULL DEFAULT now(),
