-- DR-006-03 = C: transition-aware guard. Legacy published rows without a backfilled model can still receive unrelated updates,
-- but new publication, source conversion into a published manual vehicle, or clearing the model on a published manual vehicle is blocked.
CREATE OR REPLACE FUNCTION guard_manual_vehicle_model_publish() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.source_type IN ('mingbang','four_s') AND NEW.formally_published_at IS NOT NULL AND NEW.vehicle_model_id IS NULL THEN
    IF TG_OP='INSERT'
       OR OLD.formally_published_at IS DISTINCT FROM NEW.formally_published_at
       OR OLD.source_type IS DISTINCT FROM NEW.source_type
       OR OLD.vehicle_model_id IS DISTINCT FROM NEW.vehicle_model_id THEN
      RAISE EXCEPTION 'VEHICLE_MODEL_REQUIRED_FOR_FORMAL_PUBLISH';
    END IF;
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_guard_manual_vehicle_model_publish
  BEFORE INSERT OR UPDATE OF formally_published_at,source_type,vehicle_model_id ON vehicles
  FOR EACH ROW EXECUTE FUNCTION guard_manual_vehicle_model_publish();

