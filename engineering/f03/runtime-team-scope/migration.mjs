async function config(discovery=false){
 const m=await manifest();
 if(m.migration_id!==ID||m.previous_structure_sha256!==PREVIOUS)throw Error('F03_2D_MANIFEST_DENY');
 if(!discovery&&(m.sql_sha256!==checksum||!/^[a-f0-9]{64}$/.test(m.structure_sha256)||m.tables!==86||m.columns!==512||m.constraints!==322||m.indexes!==132))throw Error('F03_2D_MANIFEST_UNPINNED');
 return m;
}
