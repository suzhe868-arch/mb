-- F03-2-2J: disposable CI-only Consultation assignee receipt, existing 000001..000009 FROZEN.
CREATE TABLE public.consultation_assignee_handover_receipts (
 receipt_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
 item_id BIGINT NOT NULL REFERENCES public.handover_items(item_id),
 batch_id BIGINT NOT NULL REFERENCES public.handover_batches(batch_id),
 consultation_id BIGINT NOT NULL REFERENCES public.consultations(consultation_id),
 customer_id BIGINT NOT NULL REFERENCES public.customers(customer_id),
 from_employee_id BIGINT NOT NULL REFERENCES public.employees(employee_id),
 to_employee_id BIGINT NOT NULL REFERENCES public.employees(employee_id),
 actor_employee_id BIGINT NOT NULL REFERENCES public.employees(employee_id),
 scope_team_id BIGINT NOT NULL REFERENCES public.teams(team_id),
 audit_id BIGINT NOT NULL REFERENCES public.audit_events(audit_id),
 request_key_sha256 TEXT NOT NULL CHECK(request_key_sha256 ~ '^[a-f0-9]{64}$'),
 committed_at TIMESTAMPTZ NOT NULL DEFAULT transaction_timestamp(),
 CONSTRAINT f03_2_2j_receipt_pk PRIMARY KEY(receipt_id),
 CONSTRAINT f03_2_2j_receipt_item_unique UNIQUE(item_id),
 CONSTRAINT f03_2_2j_receipt_request_key_unique UNIQUE(request_key_sha256),
 CONSTRAINT f03_2_2j_receipt_audit_unique UNIQUE(audit_id),
 CONSTRAINT f03_2_2j_receipt_distinct_people CHECK(from_employee_id<>to_employee_id)
);
CREATE TRIGGER f03_2_2j_receipt_append_only BEFORE UPDATE OR DELETE
 ON public.consultation_assignee_handover_receipts FOR EACH ROW
 EXECUTE FUNCTION public.f02_forbid_history_mutation();
