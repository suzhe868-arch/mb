-- PDM-13 reliable Priority TTL scheduling queue for disposable PG16 only.
-- Queue persistence is real; production scheduler/issuer remains outside this test carrier.
CREATE TABLE public.f05_priority_schedule_jobs_test (
 job_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 priority_id bigint NOT NULL UNIQUE REFERENCES public.priority_leases(priority_id) ON DELETE RESTRICT,
 vehicle_id bigint NOT NULL REFERENCES public.vehicles(vehicle_id) ON DELETE RESTRICT,
 due_at timestamptz NOT NULL,
 state text NOT NULL DEFAULT 'pending' CHECK(state IN ('pending','claimed','done')),
 attempts integer NOT NULL DEFAULT 0 CHECK(attempts>=0 AND attempts<=1000),
 next_attempt_at timestamptz NOT NULL,
 lease_token text,
 lease_until timestamptz,
 last_error_code text,
 created_at timestamptz NOT NULL DEFAULT statement_timestamp(),
 completed_at timestamptz,
 CHECK((state='claimed')=(lease_token IS NOT NULL AND lease_until IS NOT NULL)),
 CHECK(state<>'done' OR completed_at IS NOT NULL)
);
CREATE INDEX f05_priority_schedule_due_test
 ON public.f05_priority_schedule_jobs_test(state,next_attempt_at,due_at,job_id);

CREATE TABLE public.f05_priority_schedule_events_test (
 event_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 job_id bigint NOT NULL REFERENCES public.f05_priority_schedule_jobs_test(job_id) ON DELETE RESTRICT,
 priority_id bigint NOT NULL REFERENCES public.priority_leases(priority_id) ON DELETE RESTRICT,
 action text NOT NULL CHECK(action IN ('ENQUEUED','CLAIMED','RECOVERED','RETRY','DONE')),
 attempt integer NOT NULL CHECK(attempt>=0),
 disposition text,
 occurred_at timestamptz NOT NULL DEFAULT statement_timestamp()
);
CREATE FUNCTION public.f05_priority_schedule_events_immutable_test() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'F05_PRIORITY_SCHEDULE_EVENT_IMMUTABLE' USING ERRCODE='23514'; END $$;
CREATE TRIGGER f05_priority_schedule_events_no_mutation_test BEFORE UPDATE OR DELETE
 ON public.f05_priority_schedule_events_test FOR EACH ROW
 EXECUTE FUNCTION public.f05_priority_schedule_events_immutable_test();

CREATE FUNCTION public.f05_priority_schedule_enqueue_test() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE j bigint;
BEGIN
 IF NEW.status='active' THEN
  INSERT INTO public.f05_priority_schedule_jobs_test
   (priority_id,vehicle_id,due_at,next_attempt_at)
  VALUES(NEW.priority_id,NEW.vehicle_id,NEW.expires_at,NEW.expires_at)
  ON CONFLICT(priority_id) DO NOTHING
  RETURNING job_id INTO j;
  IF j IS NOT NULL THEN
   INSERT INTO public.f05_priority_schedule_events_test(job_id,priority_id,action,attempt,disposition)
   VALUES(j,NEW.priority_id,'ENQUEUED',0,'TTL_DUE');
  END IF;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER f05_priority_schedule_enqueue_after_insert_test
 AFTER INSERT ON public.priority_leases
 FOR EACH ROW EXECUTE FUNCTION public.f05_priority_schedule_enqueue_test();

REVOKE ALL ON public.f05_priority_schedule_jobs_test,public.f05_priority_schedule_events_test FROM PUBLIC;
