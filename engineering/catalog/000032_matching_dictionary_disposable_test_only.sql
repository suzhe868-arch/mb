-- F05-7 PDM12/PDM22. Strictly disposable PG16 only; never deploy as formal authority.
CREATE TABLE public.f05_matching_rule_manage_scope_test (
 employee_id bigint PRIMARY KEY REFERENCES public.employees(employee_id) ON DELETE RESTRICT,
 can_manage boolean NOT NULL CHECK(can_manage=true),
 issuer text NOT NULL DEFAULT 'DISPOSABLE_TEST_ONLY' CHECK(issuer='DISPOSABLE_TEST_ONLY'),
 expires_at timestamptz NOT NULL
);
CREATE TABLE public.f05_matching_dictionary_rules_test (
 rule_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 token text NOT NULL CHECK(length(token) BETWEEN 2 AND 60),
 mapped_key text NOT NULL CHECK(mapped_key IN('brandId','minModelYear','maxMileageKm','budgetCents','interiorColor')),
 mapped_value text NOT NULL CHECK(length(mapped_value) BETWEEN 1 AND 50),
 scope_kind text NOT NULL CHECK(scope_kind IN ('global','brand','series','series_year','model_year')),
 brand_id bigint REFERENCES public.vehicle_brands(brand_id) ON DELETE RESTRICT,
 series_id bigint REFERENCES public.vehicle_series(series_id) ON DELETE RESTRICT,
 model_id bigint REFERENCES public.vehicle_models(model_id) ON DELETE RESTRICT,
 year_from integer CHECK(year_from BETWEEN 1886 AND 2200),
 year_to integer CHECK(year_to BETWEEN 1886 AND 2200),
 status text NOT NULL DEFAULT 'enabled' CHECK(status IN('enabled','disabled','deprecated')),
 version bigint NOT NULL DEFAULT 1 CHECK(version>0),
 notes text NOT NULL DEFAULT '' CHECK(length(notes)<=200),
 created_by bigint NOT NULL REFERENCES public.employees(employee_id) ON DELETE RESTRICT,
 updated_by bigint NOT NULL REFERENCES public.employees(employee_id) ON DELETE RESTRICT,
 created_at timestamptz NOT NULL DEFAULT statement_timestamp(),
 updated_at timestamptz NOT NULL DEFAULT statement_timestamp(),
 CONSTRAINT f05_matching_dictionary_scope_test CHECK(
  (scope_kind='global' AND brand_id IS NULL AND series_id IS NULL AND model_id IS NULL AND year_from IS NULL AND year_to IS NULL)
  OR (scope_kind='brand' AND brand_id IS NOT NULL AND series_id IS NULL AND model_id IS NULL AND year_from IS NULL AND year_to IS NULL)
  OR (scope_kind='series' AND brand_id IS NULL AND series_id IS NOT NULL AND model_id IS NULL AND year_from IS NULL AND year_to IS NULL)
  OR (scope_kind='series_year' AND brand_id IS NULL AND series_id IS NOT NULL AND model_id IS NULL AND year_from IS NOT NULL AND year_to IS NOT NULL AND year_from<=year_to)
  OR (scope_kind='model_year' AND brand_id IS NULL AND series_id IS NULL AND model_id IS NOT NULL AND year_from IS NOT NULL AND year_to=year_from)
 )
);
CREATE INDEX f05_dictionary_token_scope_test ON public.f05_matching_dictionary_rules_test(token,status,scope_kind);
CREATE TABLE public.f05_matching_dictionary_history_test (
 event_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 event_key text NOT NULL UNIQUE CHECK(event_key ~ '^[A-Za-z0-9_-]{24,64}$'),
 payload_sha256 text NOT NULL CHECK(payload_sha256 ~ '^[0-9a-f]{64}$'),
 actor_employee_id bigint NOT NULL REFERENCES public.employees(employee_id) ON DELETE RESTRICT,
 rule_id bigint NOT NULL REFERENCES public.f05_matching_dictionary_rules_test(rule_id) ON DELETE RESTRICT,
 action text NOT NULL CHECK(action IN ('CREATE','EDIT','ENABLE','DISABLE','DEPRECATE')),
 before_json jsonb,
 after_json jsonb NOT NULL,
 occurred_at timestamptz NOT NULL DEFAULT statement_timestamp()
);
CREATE FUNCTION public.f05_matching_dictionary_immutable_test() RETURNS trigger LANGUAGE plpgsql AS $f05dict$
BEGIN RAISE EXCEPTION 'F05_DICTIONARY_HISTORY_IMMUTABLE' USING ERRCODE='23514'; END $f05dict$;
CREATE TRIGGER f05_matching_dictionary_history_immutable_test
 BEFORE UPDATE OR DELETE ON public.f05_matching_dictionary_history_test
 FOR EACH ROW EXECUTE FUNCTION public.f05_matching_dictionary_immutable_test();
REVOKE ALL ON public.f05_matching_rule_manage_scope_test,
 public.f05_matching_dictionary_rules_test,public.f05_matching_dictionary_history_test FROM PUBLIC;
