-- F05-6 PDM-11 disposable-only Demand lifecycle. Not an M94/production migration.
CREATE TABLE public.f05_demand_lifecycle_scope_test(
 employee_id bigint NOT NULL REFERENCES public.employees(employee_id),
 customer_id bigint NOT NULL REFERENCES public.customers(customer_id),
 can_manage_demand boolean NOT NULL CHECK(can_manage_demand=true),
 issuer text NOT NULL DEFAULT 'DISPOSABLE_TEST_ONLY' CHECK(issuer='DISPOSABLE_TEST_ONLY'),
 expires_at timestamptz NOT NULL,
 PRIMARY KEY(employee_id,customer_id)
);
CREATE TABLE public.f05_demand_end_requests_test(
 request_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 demand_id bigint NOT NULL REFERENCES public.demands(demand_id) ON DELETE RESTRICT,
 customer_id bigint NOT NULL REFERENCES public.customers(customer_id),
 event_key text NOT NULL UNIQUE,
 status text NOT NULL CHECK(status IN ('pending','processed')),
 decision text CHECK(decision IN ('completed','cancelled')),
 created_at timestamptz NOT NULL DEFAULT statement_timestamp(),
 processed_at timestamptz,
 processed_by_employee_id bigint REFERENCES public.employees(employee_id),
 CHECK((status='pending' AND processed_at IS NULL AND decision IS NULL AND processed_by_employee_id IS NULL)
    OR (status='processed' AND processed_at IS NOT NULL AND decision IS NOT NULL AND processed_by_employee_id IS NOT NULL))
);
CREATE UNIQUE INDEX f05_demand_one_pending_end_request_test
 ON public.f05_demand_end_requests_test(demand_id) WHERE status='pending';
CREATE TABLE public.f05_demand_lifecycle_events_test(
 event_key text PRIMARY KEY CHECK(event_key ~ '^[A-Za-z0-9_-]{24,64}$'),
 payload_sha256 text NOT NULL CHECK(payload_sha256 ~ '^[0-9a-f]{64}$'),
 demand_id bigint NOT NULL REFERENCES public.demands(demand_id) ON DELETE RESTRICT,
 actor_kind text NOT NULL CHECK(actor_kind IN ('customer','employee')),
 actor_id bigint NOT NULL,
 action text NOT NULL CHECK(action IN ('PAUSE','RESUME','END_REQUEST','COMPLETE','CANCEL')),
 prior_state text NOT NULL,
 result_state text NOT NULL,
 result_code text NOT NULL,
 occurred_at timestamptz NOT NULL DEFAULT statement_timestamp()
);
-- Existing immutable-event function belongs to the disposable F05 fixture.
CREATE TRIGGER f05_demand_lifecycle_events_no_mutation_test
 BEFORE UPDATE OR DELETE ON public.f05_demand_lifecycle_events_test
 FOR EACH ROW EXECUTE FUNCTION public.f05_find_car_events_immutable_test();
REVOKE ALL ON public.f05_demand_lifecycle_scope_test,
 public.f05_demand_end_requests_test,public.f05_demand_lifecycle_events_test FROM PUBLIC;
