-- PDM-15 auditable real-human-response test carrier. Never a production message/phone issuer.
ALTER TABLE public.f05_catalog_employee_consultation_scope_test
 ADD COLUMN can_record_human_response boolean NOT NULL DEFAULT false;

CREATE TABLE public.f05_consultation_human_response_events_test (
 event_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 event_key text NOT NULL UNIQUE CHECK(event_key ~ '^[A-Za-z0-9_-]{24,64}$'),
 payload_sha256 text NOT NULL CHECK(payload_sha256 ~ '^[0-9a-f]{64}$'),
 consultation_id bigint NOT NULL REFERENCES public.consultations(consultation_id) ON DELETE RESTRICT,
 actor_employee_id bigint NOT NULL REFERENCES public.employees(employee_id) ON DELETE RESTRICT,
 channel text NOT NULL CHECK(channel IN ('message','phone','offline')),
 source_fact_ref text NOT NULL CHECK(length(source_fact_ref) BETWEEN 8 AND 200),
 is_first_response boolean NOT NULL,
 occurred_at timestamptz NOT NULL,
 issuer text NOT NULL DEFAULT 'DISPOSABLE_TEST_ONLY' CHECK(issuer='DISPOSABLE_TEST_ONLY')
);
CREATE UNIQUE INDEX f05_one_first_human_response_test
 ON public.f05_consultation_human_response_events_test(consultation_id)
 WHERE is_first_response=true;
CREATE FUNCTION public.f05_human_response_immutable_test() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'F05_HUMAN_RESPONSE_IMMUTABLE' USING ERRCODE='23514'; END $$;
CREATE TRIGGER f05_human_response_events_immutable_test BEFORE UPDATE OR DELETE
 ON public.f05_consultation_human_response_events_test FOR EACH ROW
 EXECUTE FUNCTION public.f05_human_response_immutable_test();
REVOKE ALL ON public.f05_consultation_human_response_events_test FROM PUBLIC;
