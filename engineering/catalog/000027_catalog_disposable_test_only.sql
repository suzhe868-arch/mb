-- Test-only Customer bearer/session, persistent favorite state and append-only audit.
-- Deliberately NOT a genuine WeChat/customer signed identity or production migration.
CREATE TABLE public.f05_catalog_customer_sessions_test (
 token_sha256 text PRIMARY KEY CHECK(token_sha256 ~ '^[0-9a-f]{64}$'),
 customer_id bigint NOT NULL REFERENCES public.customers(customer_id) ON DELETE RESTRICT,
 issuer text NOT NULL DEFAULT 'DISPOSABLE_TEST_ONLY' CHECK(issuer='DISPOSABLE_TEST_ONLY'),
 expires_at timestamptz NOT NULL,
 revoked_at timestamptz,
 issued_at timestamptz NOT NULL DEFAULT statement_timestamp()
);
CREATE TABLE public.f05_catalog_favorite_states_test (
 customer_id bigint NOT NULL REFERENCES public.customers(customer_id) ON DELETE RESTRICT,
 vehicle_id bigint NOT NULL REFERENCES public.vehicles(vehicle_id) ON DELETE RESTRICT,
 current_state text NOT NULL CHECK(current_state IN ('active','removed')),
 state_version bigint NOT NULL DEFAULT 1 CHECK(state_version>0),
 created_at timestamptz NOT NULL DEFAULT statement_timestamp(),
 changed_at timestamptz NOT NULL DEFAULT statement_timestamp(),
 PRIMARY KEY(customer_id,vehicle_id)
);
CREATE TABLE public.f05_catalog_favorite_events_test (
 event_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 customer_id bigint NOT NULL,
 vehicle_id bigint NOT NULL,
 event_key text NOT NULL UNIQUE CHECK(event_key ~ '^[A-Za-z0-9_-]{24,64}$'),
 payload_sha256 text NOT NULL CHECK(payload_sha256 ~ '^[0-9a-f]{64}$'),
 action text NOT NULL CHECK(action IN ('ADD','REMOVE')),
 outcome text NOT NULL CHECK(outcome IN ('APPLIED','NOOP')),
 after_state text NOT NULL CHECK(after_state IN ('active','removed')),
 state_version bigint NOT NULL CHECK(state_version>0),
 created_at timestamptz NOT NULL DEFAULT statement_timestamp(),
 FOREIGN KEY(customer_id,vehicle_id) REFERENCES public.f05_catalog_favorite_states_test(customer_id,vehicle_id)
);
CREATE FUNCTION public.f05_catalog_immutable_favorite_event_test() RETURNS trigger LANGUAGE plpgsql AS $$
 BEGIN RAISE EXCEPTION 'F05_FAVORITE_APPEND_ONLY_TEST' USING ERRCODE='23514'; END $$;
CREATE TRIGGER f05_catalog_favorite_event_no_mutation_test BEFORE UPDATE OR DELETE
 ON public.f05_catalog_favorite_events_test FOR EACH ROW
 EXECUTE FUNCTION public.f05_catalog_immutable_favorite_event_test();
REVOKE ALL ON public.f05_catalog_customer_sessions_test,public.f05_catalog_favorite_states_test,public.f05_catalog_favorite_events_test FROM PUBLIC;

