-- Trigger fires on actual persisted Customer account transition, not a synthetic HTTP request.
-- Guarantees newly disabled Customers' open Consultations have a hold, even without SLA proof.
CREATE FUNCTION public.f05_customer_disable_hold_test() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.account_status='disabled' AND OLD.account_status IS DISTINCT FROM NEW.account_status THEN
  WITH changed AS (
   INSERT INTO public.f05_catalog_consultation_hold_test
    (consultation_id,active,version,paused_at,remaining_ms)
   SELECT c.consultation_id,true,1,statement_timestamp(),
      CASE WHEN sla.first_human_response_at IS NULL AND sla.consultation_id IS NOT NULL
       THEN GREATEST(0,FLOOR(EXTRACT(EPOCH FROM (sla.effective_deadline-statement_timestamp()))*1000))::bigint
       ELSE NULL END
   FROM public.consultations c
   LEFT JOIN public.f05_catalog_consultation_sla_test sla ON sla.consultation_id=c.consultation_id
   WHERE c.customer_id=NEW.customer_id AND c.status IN ('pending','processing')
   ON CONFLICT (consultation_id) DO UPDATE
    SET active=true,version=public.f05_catalog_consultation_hold_test.version+1,
        paused_at=excluded.paused_at,remaining_ms=excluded.remaining_ms,
        resumed_at=NULL,resumed_by_employee_id=NULL
   WHERE public.f05_catalog_consultation_hold_test.active=false
   RETURNING consultation_id,version,remaining_ms
  )
  INSERT INTO public.f05_catalog_consultation_hold_events_test(consultation_id,action,hold_version,remaining_ms)
   SELECT consultation_id,'HOLD_STARTED',version,remaining_ms FROM changed;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER f05_customer_disable_hold_test AFTER UPDATE OF account_status ON public.customers
 FOR EACH ROW EXECUTE FUNCTION public.f05_customer_disable_hold_test();
ALTER TABLE public.f05_catalog_employee_consultation_scope_test ADD COLUMN can_resume_hold boolean NOT NULL DEFAULT false;
REVOKE ALL ON public.f05_catalog_consultation_sla_test,public.f05_catalog_consultation_hold_test,
 public.f05_catalog_consultation_hold_events_test FROM PUBLIC;
