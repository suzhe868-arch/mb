-- The old Lock/Transaction source remains authoritative. New v24 can only
-- close its own CI Priority row; never changes either signed business table.
CREATE FUNCTION public.f05_8_close_for_occupancy() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE occupied_vehicle BIGINT; occupied_cycle BIGINT; reason TEXT;
BEGIN
 IF TG_TABLE_NAME='locks' THEN
  IF TG_OP='DELETE' THEN RETURN OLD; END IF;
  IF NEW.lock_status<>'active' OR NEW.expires_at<=statement_timestamp() THEN
    -- R06: occupancy exit never resurrects ended rows; recompute only this
    -- previously occupied Vehicle/cycle, reading freshly signed current Match.
    IF TG_OP='UPDATE' AND
       (OLD.lock_status IS DISTINCT FROM NEW.lock_status OR OLD.expires_at IS DISTINCT FROM NEW.expires_at) THEN
      PERFORM public.f05_8_reconcile_scope_ci(NEW.vehicle_id,NEW.listing_cycle_id);
    END IF;
    RETURN NEW;
   END IF;
  occupied_vehicle:=NEW.vehicle_id;occupied_cycle:=NEW.listing_cycle_id;
  reason:='lock_takeover';
 ELSIF TG_TABLE_NAME='transactions' THEN
  IF TG_OP='DELETE' THEN RETURN OLD; END IF;
  IF NEW.status NOT IN ('trading','in_progress','pending','active') THEN
    IF TG_OP='UPDATE' AND OLD.status IS DISTINCT FROM NEW.status THEN
      PERFORM public.f05_8_reconcile_scope_ci(NEW.vehicle_id,NEW.listing_cycle_id);
    END IF;
    RETURN NEW;
   END IF;
  occupied_vehicle:=NEW.vehicle_id;occupied_cycle:=NEW.listing_cycle_id;
  reason:='transaction_started';
 ELSE RETURN COALESCE(NEW,OLD); END IF;
 -- Mandatory serialization with every new Priority arbitration, which locks
 -- this same signed Vehicle first. The occupancy trigger must never miss a
 -- concurrent uncommitted newly granted Priority lease.
 PERFORM 1 FROM public.vehicles WHERE vehicle_id=occupied_vehicle FOR UPDATE;
 UPDATE public.f05_8_priority_ci SET status='ended',ended_at=transaction_timestamp(),
 ended_reason=CASE WHEN reason='lock_takeover' AND customer_id=NEW.customer_id
 THEN 'converted_to_lock' ELSE reason END
 WHERE vehicle_id=occupied_vehicle AND listing_cycle_id=occupied_cycle AND status='active';
 RETURN NEW;
END $$;
CREATE TRIGGER f05_8_new_lock_closes_priority AFTER INSERT OR UPDATE OF lock_status,expires_at ON public.locks
 FOR EACH ROW EXECUTE FUNCTION public.f05_8_close_for_occupancy();
CREATE TRIGGER f05_8_new_transaction_closes_priority AFTER INSERT OR UPDATE OF status ON public.transactions
 FOR EACH ROW EXECUTE FUNCTION public.f05_8_close_for_occupancy();
