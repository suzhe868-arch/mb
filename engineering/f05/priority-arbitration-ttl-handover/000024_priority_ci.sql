CREATE FUNCTION public.f05_8_priority_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF TG_OP='DELETE' THEN RAISE EXCEPTION 'F05_8_PRIORITY_HISTORY_DELETE_DENIED' USING ERRCODE='23514'; END IF;
 IF OLD.priority_id IS DISTINCT FROM NEW.priority_id OR
    OLD.customer_id IS DISTINCT FROM NEW.customer_id OR
    OLD.vehicle_id IS DISTINCT FROM NEW.vehicle_id OR
    OLD.listing_cycle_id IS DISTINCT FROM NEW.listing_cycle_id OR
    OLD.created_at IS DISTINCT FROM NEW.created_at OR
    OLD.expires_at IS DISTINCT FROM NEW.expires_at OR
    OLD.creation_key IS DISTINCT FROM NEW.creation_key OR
    OLD.source_marker IS DISTINCT FROM NEW.source_marker OR
    OLD.ended_at IS NOT NULL OR OLD.status='ended'
 THEN RAISE EXCEPTION 'F05_8_PRIORITY_TTL_OR_IMMUTABLE_HISTORY' USING ERRCODE='23514'; END IF;
 IF NEW.status='active' AND (NEW.ended_at IS NOT NULL OR NEW.ended_reason IS NOT NULL) THEN
  RAISE EXCEPTION 'F05_8_INVALID_ACTIVE_PRIORITY' USING ERRCODE='23514'; END IF;
 IF NEW.status='ended' AND (NEW.ended_at IS NULL OR NEW.ended_reason IS NULL) THEN
  RAISE EXCEPTION 'F05_8_INVALID_ENDING' USING ERRCODE='23514'; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER f05_8_priority_append_history BEFORE UPDATE OR DELETE ON public.f05_8_priority_ci
 FOR EACH ROW EXECUTE FUNCTION public.f05_8_priority_guard();
-- The old Lock/Transaction source remains authoritative. New v24 can only
-- close its own CI Priority row; never changes either signed business table.
CREATE FUNCTION public.f05_8_close_for_occupancy() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE occupied_vehicle BIGINT; occupied_cycle BIGINT; reason TEXT;
BEGIN
 IF TG_TABLE_NAME='locks' THEN
  IF TG_OP='DELETE' THEN RETURN OLD; END IF;
  IF NEW.lock_status<>'active' OR NEW.expires_at<=statement_timestamp() THEN RETURN NEW; END IF;
  occupied_vehicle:=NEW.vehicle_id;occupied_cycle:=NEW.listing_cycle_id;
  reason:='lock_takeover';
 ELSIF TG_TABLE_NAME='transactions' THEN
  IF TG_OP='DELETE' THEN RETURN OLD; END IF;
  IF NEW.status NOT IN ('trading','in_progress','pending','active') THEN RETURN NEW; END IF;
  occupied_vehicle:=NEW.vehicle_id;occupied_cycle:=NEW.listing_cycle_id;
  reason:='transaction_started';
 ELSE RETURN COALESCE(NEW,OLD); END IF;
 -- Mandatory serialization with every new Priority arbitration, which locks
 -- this same signed Vehicle first. The occupancy trigger must never miss a
 -- concurrent uncommitted newly granted Priority lease.
 PERFORM 1 FROM public.vehicles WHERE vehicle_id=occupied_vehicle FOR UPDATE;
 UPDATE public.f05_8_priority_ci SET status='ended',ended_at=transaction_timestamp(),
 ended_reason=reason WHERE vehicle_id=occupied_vehicle AND listing_cycle_id=occupied_cycle AND status='active';
 RETURN NEW;
END $$;
CREATE TRIGGER f05_8_new_lock_closes_priority AFTER INSERT OR UPDATE OF lock_status,expires_at ON public.locks
 FOR EACH ROW EXECUTE FUNCTION public.f05_8_close_for_occupancy();
CREATE TRIGGER f05_8_new_transaction_closes_priority AFTER INSERT OR UPDATE OF status ON public.transactions
 FOR EACH ROW EXECUTE FUNCTION public.f05_8_close_for_occupancy();
