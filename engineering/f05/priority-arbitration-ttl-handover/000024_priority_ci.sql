-- R10: signed operator must have live authority over the ACTUAL Priority
-- business object, never merely the caller-supplied teamId.
CREATE FUNCTION public.f05_8_actor_priority_scope_ci(pid BIGINT,eid BIGINT,role TEXT,requested_team BIGINT)
RETURNS BOOLEAN LANGUAGE sql STABLE AS $$
 SELECT EXISTS(SELECT 1 FROM public.f05_8_priority_ci p
 JOIN public.demands d ON d.demand_id=p.trigger_demand_id AND d.customer_id=p.customer_id
 JOIN public.customers cs ON cs.customer_id=p.customer_id
 LEFT JOIN public.f05_8_handover_ci h ON h.priority_id=p.priority_id
 JOIN public.teams t ON t.team_id=p.origin_team_id AND t.team_id=requested_team
  AND t.store_id=p.origin_store_id AND t.team_status='active'
 JOIN public.stores st ON st.store_id=p.origin_store_id AND st.status='active'
 JOIN public.employees e ON e.employee_id=eid AND e.employment_status='active'
 LEFT JOIN public.employee_team_memberships m ON m.employee_id=eid AND m.team_id=t.team_id
  AND m.valid_from<=statement_timestamp() AND (m.ended_at IS NULL OR m.ended_at>statement_timestamp())
 JOIN public.permissions pe ON pe.permission_code='matching.rule.manage.ci.synthetic'
 JOIN public.employee_permission_overrides ov ON ov.employee_id=eid AND ov.permission_id=pe.permission_id AND ov.decision='allow'
 JOIN public.employee_capability_scope_bindings b ON b.employee_id=eid AND b.permission_id=pe.permission_id
  AND b.granted_at<=statement_timestamp() AND (b.ended_at IS NULL OR b.ended_at>statement_timestamp())
 JOIN public.employee_data_scopes sc ON sc.scope_id=b.scope_id AND sc.employee_id=eid AND sc.ended_at IS NULL
 WHERE p.priority_id=pid AND role IN ('sales','manager','store_head')
  AND ((role IN ('manager','store_head') AND
       ((sc.scope_kind='team' AND sc.scope_reference_id=t.team_id)
        OR (sc.scope_kind='store' AND sc.scope_reference_id=st.store_id)))
    OR (role='sales' AND e.store_id=t.store_id AND m.employee_id=eid
      AND sc.scope_kind='team' AND sc.scope_reference_id=t.team_id))
  -- R13: historic Priority or original Handover owner cannot regain rights.
  AND (role IN ('manager','store_head') OR
    (p.responsible_employee_id=eid AND d.responsible_employee_id=eid
      AND cs.current_owner_employee_id=eid AND cs.owner_assignment_state='assigned')));
$$;
CREATE FUNCTION public.f05_8_actor_demand_scope_ci(did BIGINT,eid BIGINT,role TEXT,requested_team BIGINT)
RETURNS BOOLEAN LANGUAGE sql STABLE AS $$
 SELECT EXISTS(SELECT 1 FROM public.demands d
 JOIN public.customers cs ON cs.customer_id=d.customer_id
 JOIN public.employees owner ON owner.employee_id=d.responsible_employee_id
 JOIN public.employee_team_memberships om ON om.employee_id=owner.employee_id
  AND om.team_id=requested_team AND om.valid_from<=statement_timestamp()
  AND (om.ended_at IS NULL OR om.ended_at>statement_timestamp())
 JOIN public.teams t ON t.team_id=om.team_id AND t.store_id=owner.store_id AND t.team_status='active'
 JOIN public.stores st ON st.store_id=t.store_id AND st.status='active'
 JOIN public.employees e ON e.employee_id=eid AND e.employment_status='active'
 LEFT JOIN public.employee_team_memberships m ON m.employee_id=eid AND m.team_id=t.team_id
  AND m.valid_from<=statement_timestamp() AND (m.ended_at IS NULL OR m.ended_at>statement_timestamp())
 JOIN public.permissions pe ON pe.permission_code='matching.rule.manage.ci.synthetic'
 JOIN public.employee_permission_overrides ov ON ov.employee_id=eid AND ov.permission_id=pe.permission_id AND ov.decision='allow'
 JOIN public.employee_capability_scope_bindings b ON b.employee_id=eid AND b.permission_id=pe.permission_id
  AND b.granted_at<=statement_timestamp() AND (b.ended_at IS NULL OR b.ended_at>statement_timestamp())
 JOIN public.employee_data_scopes sc ON sc.scope_id=b.scope_id AND sc.employee_id=eid AND sc.ended_at IS NULL
 WHERE d.demand_id=did AND role IN ('sales','manager','store_head')
 AND ((role IN ('manager','store_head') AND
      ((sc.scope_kind='team' AND sc.scope_reference_id=t.team_id)
       OR (sc.scope_kind='store' AND sc.scope_reference_id=st.store_id)))
   OR (role='sales' AND e.store_id=t.store_id AND m.employee_id=eid
     AND sc.scope_kind='team' AND sc.scope_reference_id=t.team_id))
 AND (role IN ('manager','store_head') OR
   (d.responsible_employee_id=eid AND cs.current_owner_employee_id=eid
     AND cs.owner_assignment_state='assigned')));
$$;
-- R02: signed-source mutation and Priority lifecycle reconcile atomically.
-- The affected Vehicle row is acquired before Priority, same as JS arbitration.
CREATE FUNCTION public.f05_8_reconcile_scope_ci(vid BIGINT,cid BIGINT)
RETURNS VOID LANGUAGE plpgsql AS $$
DECLARE held public.f05_8_priority_ci%ROWTYPE;
 candidate RECORD; successor RECORD; reason TEXT; is_due BOOLEAN; candidate_found BOOLEAN;
BEGIN
 PERFORM 1 FROM public.vehicles WHERE vehicle_id=vid FOR UPDATE;
 SELECT * INTO held FROM public.f05_8_priority_ci
  WHERE vehicle_id=vid AND listing_cycle_id=cid AND status='active' FOR UPDATE;
 IF FOUND THEN
  is_due:=held.expires_at<=statement_timestamp();
  -- R07: after a formal completed transfer, the signed Demand keeps its
  -- provenance, while the successor owns this SAME unextended lease.
  -- Do not silently switch it back to a formerly disabled Employee.
  IF NOT is_due AND public.f05_8_handover_source_valid_ci(held.priority_id)
   AND public.f05_8_responsible_object_scope_ci(held.priority_id,held.responsible_employee_id)
   AND EXISTS(SELECT 1 FROM public.f05_8_handover_ci h
    WHERE h.priority_id=held.priority_id AND h.state='completed'
      AND h.new_responsible_employee_id=held.responsible_employee_id)
   AND NOT EXISTS(SELECT 1 FROM public.locks lk WHERE lk.vehicle_id=vid AND lk.listing_cycle_id=cid
     AND lk.lock_status='active' AND lk.expires_at>statement_timestamp())
   AND NOT EXISTS(SELECT 1 FROM public.transactions t WHERE t.vehicle_id=vid AND t.listing_cycle_id=cid
     AND t.status IN ('trading','in_progress','pending','active')) THEN
    RETURN;
  END IF;
  IF NOT is_due AND public.f05_8_pending_source_ci(held.priority_id)
    AND EXISTS(SELECT 1 FROM public.f05_8_handover_ci h WHERE h.priority_id=held.priority_id AND h.state IN ('pending','failed'))
    AND NOT EXISTS(SELECT 1 FROM public.locks l WHERE l.vehicle_id=vid AND l.listing_cycle_id=cid AND l.lock_status='active' AND l.expires_at>statement_timestamp())
    AND NOT EXISTS(SELECT 1 FROM public.transactions t WHERE t.vehicle_id=vid AND t.listing_cycle_id=cid AND t.status IN ('trading','in_progress','pending','active')) THEN RETURN; END IF;
   SELECT * INTO candidate FROM public.f05_8_eligible_candidates_ci
   WHERE vehicle_id=vid AND listing_cycle_id=cid AND customer_id=held.customer_id
   ORDER BY CASE tier WHEN 'high' THEN 0 ELSE 1 END,created_at,demand_id,result_id LIMIT 1;
  candidate_found:=FOUND;
  -- A second pure Employee/Scope loss must create a formal Batch in the
  -- very same source COMMIT. It may not release the still-entitled Customer
  -- to another Customer merely because the old Employee lost authorization.
  IF NOT is_due AND NOT public.f05_8_responsible_authorized_ci(held.responsible_employee_id)
     AND public.f05_8_handover_source_valid_ci(held.priority_id)
     AND NOT EXISTS(SELECT 1 FROM public.locks WHERE vehicle_id=vid AND listing_cycle_id=cid
       AND lock_status='active' AND expires_at>statement_timestamp())
     AND NOT EXISTS(SELECT 1 FROM public.transactions WHERE vehicle_id=vid AND listing_cycle_id=cid
       AND status IN ('trading','in_progress','pending','active')) THEN
    INSERT INTO public.f05_8_handover_ci(priority_id,original_responsible_employee_id)
      VALUES(held.priority_id,held.responsible_employee_id)
      ON CONFLICT(priority_id) DO NOTHING;
    INSERT INTO public.f05_8_events_ci(priority_id,customer_id,vehicle_id,event_kind,before_json,after_json,event_key)
      VALUES(held.priority_id,held.customer_id,vid,'handover_initiated',
        jsonb_build_object('responsible',held.responsible_employee_id),
        jsonb_build_object('sourceCOMMIT',true,'ttlUnchanged',true),
        'source-handover:'||held.priority_id::text)
      ON CONFLICT(event_key) DO NOTHING;
    RETURN;
  END IF;
  IF is_due OR NOT candidate_found
    OR EXISTS(SELECT 1 FROM public.locks WHERE vehicle_id=vid AND listing_cycle_id=cid
       AND lock_status='active' AND expires_at>statement_timestamp())
    OR EXISTS(SELECT 1 FROM public.transactions WHERE vehicle_id=vid AND listing_cycle_id=cid
       AND status IN ('trading','in_progress','pending','active')) THEN
   reason:=CASE WHEN is_due THEN 'ttl_expired'
     WHEN EXISTS(SELECT 1 FROM public.locks lk WHERE lk.vehicle_id=vid AND lk.listing_cycle_id=cid
       AND lk.lock_status='active' AND lk.expires_at>statement_timestamp() AND lk.customer_id=held.customer_id)
       THEN 'converted_to_lock'
     WHEN EXISTS(SELECT 1 FROM public.locks lk WHERE lk.vehicle_id=vid AND lk.listing_cycle_id=cid
       AND lk.lock_status='active' AND lk.expires_at>statement_timestamp()) THEN 'lock_takeover'
     WHEN EXISTS(SELECT 1 FROM public.transactions tr WHERE tr.vehicle_id=vid AND tr.listing_cycle_id=cid
       AND tr.status IN ('trading','in_progress','pending','active')) THEN 'transaction_started'
     WHEN EXISTS(SELECT 1 FROM public.vehicles WHERE vehicle_id=vid AND
       (source_sale_status<>'active' OR archived_at IS NOT NULL))
       OR EXISTS(SELECT 1 FROM public.vehicle_listing_cycles WHERE listing_cycle_id=cid AND ended_at IS NOT NULL)
      THEN 'vehicle_unavailable' ELSE 'match_invalidated' END;
   UPDATE public.f05_8_priority_ci SET status='ended',ended_at=transaction_timestamp(),
    ended_reason=reason WHERE priority_id=held.priority_id AND status='active';
   INSERT INTO public.f05_8_events_ci(priority_id,customer_id,vehicle_id,event_kind,before_json,after_json,event_key)
    VALUES(held.priority_id,held.customer_id,vid,'ended',
     jsonb_build_object('trigger',held.trigger_demand_id),jsonb_build_object('reason',reason),
     'source-end:'||gen_random_uuid()::text);
   IF is_due THEN
    INSERT INTO public.f05_8_suppression_ci(customer_id,vehicle_id,listing_cycle_id,
     suppressed_source_signature,original_priority_id,reason)
     VALUES(held.customer_id,vid,cid,held.source_signature,held.priority_id,'ttl_expired')
     ON CONFLICT(customer_id,vehicle_id,listing_cycle_id) DO UPDATE SET
       suppressed_source_signature=excluded.suppressed_source_signature,
       original_priority_id=excluded.original_priority_id,reason=excluded.reason,recorded_at=transaction_timestamp();
    INSERT INTO public.f05_8_suppressed_facts_ci(customer_id,vehicle_id,listing_cycle_id,
     source_signature,original_priority_id,reason)
     SELECT held.customer_id,vid,cid,r.source_signature,held.priority_id,'ttl_expired'
      FROM public.f05_7_result_versions_ci r JOIN public.demands d ON d.demand_id=r.demand_id
      WHERE d.customer_id=held.customer_id AND r.vehicle_id=vid AND r.listing_cycle_id=cid
      ON CONFLICT DO NOTHING;
    INSERT INTO public.f05_8_suppressed_facts_ci(customer_id,vehicle_id,listing_cycle_id,
     source_signature,original_priority_id,reason)
     VALUES(held.customer_id,vid,cid,held.source_signature,held.priority_id,'ttl_expired')
     ON CONFLICT DO NOTHING;
   END IF;
  ELSE
   IF held.trigger_demand_id IS DISTINCT FROM candidate.demand_id
      OR held.source_match_result_id IS DISTINCT FROM candidate.result_id
      OR held.responsible_employee_id IS DISTINCT FROM candidate.responsible_employee_id THEN
    UPDATE public.f05_8_priority_ci SET trigger_demand_id=candidate.demand_id,
      source_match_result_id=candidate.result_id,responsible_employee_id=candidate.responsible_employee_id,
      source_signature=candidate.source_signature WHERE priority_id=held.priority_id;
    INSERT INTO public.f05_8_events_ci(priority_id,customer_id,vehicle_id,event_kind,before_json,after_json,event_key)
     VALUES(held.priority_id,held.customer_id,vid,'trigger_demand_replaced',
      jsonb_build_object('demandId',held.trigger_demand_id),
      jsonb_build_object('demandId',candidate.demand_id,'ttlUnchanged',true),
      'source-replace:'||gen_random_uuid()::text);
   END IF;
   RETURN;
  END IF;
 END IF;
 IF EXISTS(SELECT 1 FROM public.locks WHERE vehicle_id=vid AND listing_cycle_id=cid
     AND lock_status='active' AND expires_at>statement_timestamp())
  OR EXISTS(SELECT 1 FROM public.transactions WHERE vehicle_id=vid AND listing_cycle_id=cid
     AND status IN ('trading','in_progress','pending','active')) THEN RETURN; END IF;
 SELECT * INTO successor FROM public.f05_8_eligible_candidates_ci
  WHERE vehicle_id=vid AND listing_cycle_id=cid
  ORDER BY CASE tier WHEN 'high' THEN 0 ELSE 1 END,created_at,demand_id,result_id LIMIT 1;
 IF FOUND AND NOT EXISTS(SELECT 1 FROM public.f05_8_priority_ci WHERE vehicle_id=vid AND listing_cycle_id=cid AND status='active') THEN
  INSERT INTO public.f05_8_priority_ci(customer_id,vehicle_id,listing_cycle_id,trigger_demand_id,
    responsible_employee_id,source_match_result_id,source_signature,expires_at,creation_key)
   SELECT successor.customer_id,vid,cid,successor.demand_id,successor.responsible_employee_id,
    successor.result_id,successor.source_signature,
    transaction_timestamp()+(ttl_seconds*interval '1 second'),'source-create:'||gen_random_uuid()::text
   FROM public.f05_8_config_ci WHERE singleton=true;
  INSERT INTO public.f05_8_events_ci(priority_id,customer_id,vehicle_id,event_kind,after_json,event_key)
   SELECT priority_id,customer_id,vehicle_id,'created',
    jsonb_build_object('triggerDemandId',trigger_demand_id,'sourceEvent',true),
    'source-created:'||gen_random_uuid()::text FROM public.f05_8_priority_ci
   WHERE vehicle_id=vid AND listing_cycle_id=cid AND status='active';
 END IF;
END $$;

CREATE FUNCTION public.f05_8_source_change_ci() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE affected RECORD;
BEGIN
 IF TG_TABLE_NAME='f05_7_result_versions_ci' THEN
  IF (TG_OP='INSERT' AND NEW.status='current')
     OR (TG_OP='UPDATE' AND NEW.status IS DISTINCT FROM OLD.status) THEN
   PERFORM public.f05_8_reconcile_scope_ci(NEW.vehicle_id,NEW.listing_cycle_id);
  END IF;
 ELSIF TG_TABLE_NAME='demands' THEN
  -- R05: not just a previously winning Demand; include still-current signed
  -- Match scopes for a newly eligible (or non-trigger) Demand with no Priority.
  FOR affected IN
   SELECT DISTINCT vehicle_id,listing_cycle_id FROM (
     SELECT p.vehicle_id,p.listing_cycle_id FROM public.f05_8_priority_ci p
      WHERE p.trigger_demand_id=NEW.demand_id AND p.status='active'
     UNION ALL
     SELECT r.vehicle_id,r.listing_cycle_id FROM public.f05_7_result_versions_ci r
      WHERE r.demand_id=NEW.demand_id AND r.status='current'
       AND r.tier IN ('high','acceptable')
   ) scopes ORDER BY vehicle_id,listing_cycle_id LOOP
   PERFORM public.f05_8_reconcile_scope_ci(affected.vehicle_id,affected.listing_cycle_id);
  END LOOP;
 ELSIF TG_TABLE_NAME='customers' THEN
  FOR affected IN
   SELECT DISTINCT vehicle_id,listing_cycle_id FROM (
    SELECT p.vehicle_id,p.listing_cycle_id FROM public.f05_8_priority_ci p
     WHERE p.customer_id=NEW.customer_id AND p.status='active'
    UNION ALL
    SELECT r.vehicle_id,r.listing_cycle_id FROM public.f05_7_result_versions_ci r
     JOIN public.demands d ON d.demand_id=r.demand_id AND d.customer_id=NEW.customer_id
     WHERE r.status='current' AND r.tier IN ('high','acceptable')
   ) scopes ORDER BY vehicle_id,listing_cycle_id LOOP
   PERFORM public.f05_8_reconcile_scope_ci(affected.vehicle_id,affected.listing_cycle_id);
  END LOOP;
 ELSIF TG_TABLE_NAME='vehicles' THEN
  FOR affected IN
   SELECT DISTINCT vehicle_id,listing_cycle_id FROM (
    SELECT p.vehicle_id,p.listing_cycle_id FROM public.f05_8_priority_ci p
     WHERE p.vehicle_id=NEW.vehicle_id AND p.status='active'
    UNION ALL
    SELECT r.vehicle_id,r.listing_cycle_id FROM public.f05_7_result_versions_ci r
     WHERE r.vehicle_id=NEW.vehicle_id AND r.status='current' AND r.tier IN ('high','acceptable')
   ) scopes ORDER BY vehicle_id,listing_cycle_id LOOP
   PERFORM public.f05_8_reconcile_scope_ci(affected.vehicle_id,affected.listing_cycle_id);
  END LOOP;
 ELSIF TG_TABLE_NAME='vehicle_listing_cycles' THEN
  PERFORM public.f05_8_reconcile_scope_ci(NEW.vehicle_id,NEW.listing_cycle_id);
 ELSIF TG_TABLE_NAME='employees' THEN
  FOR affected IN SELECT DISTINCT vehicle_id,listing_cycle_id FROM public.f05_8_priority_ci
    WHERE responsible_employee_id=NEW.employee_id AND status='active' LOOP
   PERFORM public.f05_8_reconcile_scope_ci(affected.vehicle_id,affected.listing_cycle_id);
  END LOOP;
 ELSIF TG_TABLE_NAME='f05_6_level_find_policy_ci' THEN
  FOR affected IN SELECT DISTINCT p.vehicle_id,p.listing_cycle_id FROM public.f05_8_priority_ci p
    JOIN public.customers cs ON cs.customer_id=p.customer_id
    WHERE cs.customer_level_id=NEW.level_id AND p.status='active' LOOP
   PERFORM public.f05_8_reconcile_scope_ci(affected.vehicle_id,affected.listing_cycle_id);
  END LOOP;
 ELSIF TG_TABLE_NAME IN ('employee_permission_overrides','employee_data_scopes',
   'employee_capability_scope_bindings','employee_team_memberships') THEN
  FOR affected IN SELECT DISTINCT vehicle_id,listing_cycle_id FROM public.f05_8_priority_ci
    WHERE responsible_employee_id=NEW.employee_id LOOP
   PERFORM public.f05_8_reconcile_scope_ci(affected.vehicle_id,affected.listing_cycle_id);
  END LOOP;

 ELSIF TG_TABLE_NAME='teams' THEN
  FOR affected IN SELECT DISTINCT p.vehicle_id,p.listing_cycle_id FROM public.f05_8_priority_ci p
    JOIN public.employee_team_memberships tm ON tm.employee_id=p.responsible_employee_id
    WHERE tm.team_id=NEW.team_id LOOP
   PERFORM public.f05_8_reconcile_scope_ci(affected.vehicle_id,affected.listing_cycle_id);
  END LOOP;
 ELSIF TG_TABLE_NAME='stores' THEN
  FOR affected IN SELECT DISTINCT p.vehicle_id,p.listing_cycle_id FROM public.f05_8_priority_ci p
    JOIN public.employees emp ON emp.employee_id=p.responsible_employee_id
    WHERE emp.store_id=NEW.store_id LOOP
   PERFORM public.f05_8_reconcile_scope_ci(affected.vehicle_id,affected.listing_cycle_id);
  END LOOP;
 END IF;
 RETURN NEW;
END $$;
CREATE CONSTRAINT TRIGGER f05_8_match_scope_ci AFTER INSERT OR UPDATE OF status ON public.f05_7_result_versions_ci
 DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION public.f05_8_source_change_ci();
CREATE CONSTRAINT TRIGGER f05_8_demand_scope_ci AFTER UPDATE OF demand_state,responsible_employee_id ON public.demands
 DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION public.f05_8_source_change_ci();
CREATE CONSTRAINT TRIGGER f05_8_customer_scope_ci AFTER UPDATE OF account_status,customer_level_id,current_owner_employee_id,owner_assignment_state ON public.customers
 DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION public.f05_8_source_change_ci();
CREATE TRIGGER f05_8_vehicle_scope_ci AFTER UPDATE OF source_sale_status,archived_at ON public.vehicles
 FOR EACH ROW EXECUTE FUNCTION public.f05_8_source_change_ci();
CREATE TRIGGER f05_8_cycle_scope_ci AFTER UPDATE OF ended_at ON public.vehicle_listing_cycles
 FOR EACH ROW EXECUTE FUNCTION public.f05_8_source_change_ci();
CREATE TRIGGER f05_8_employee_scope_ci AFTER UPDATE OF employment_status,store_id ON public.employees
 FOR EACH ROW EXECUTE FUNCTION public.f05_8_source_change_ci();
CREATE TRIGGER f05_8_find_scope_ci AFTER UPDATE OF find_enabled ON public.f05_6_level_find_policy_ci
 FOR EACH ROW EXECUTE FUNCTION public.f05_8_source_change_ci();
CREATE TRIGGER f05_8_permission_scope_ci AFTER UPDATE OF decision ON public.employee_permission_overrides
 FOR EACH ROW EXECUTE FUNCTION public.f05_8_source_change_ci();

CREATE TRIGGER f05_8_scope_binding_ci AFTER UPDATE OF ended_at
 ON public.employee_capability_scope_bindings FOR EACH ROW EXECUTE FUNCTION public.f05_8_source_change_ci();
CREATE TRIGGER f05_8_scope_fact_ci AFTER UPDATE OF ended_at
 ON public.employee_data_scopes FOR EACH ROW EXECUTE FUNCTION public.f05_8_source_change_ci();
CREATE TRIGGER f05_8_team_membership_ci AFTER UPDATE OF ended_at,team_id
 ON public.employee_team_memberships FOR EACH ROW EXECUTE FUNCTION public.f05_8_source_change_ci();
CREATE TRIGGER f05_8_team_state_ci AFTER UPDATE OF team_status,store_id
 ON public.teams FOR EACH ROW EXECUTE FUNCTION public.f05_8_source_change_ci();
CREATE TRIGGER f05_8_store_state_ci AFTER UPDATE OF status
 ON public.stores FOR EACH ROW EXECUTE FUNCTION public.f05_8_source_change_ci();
