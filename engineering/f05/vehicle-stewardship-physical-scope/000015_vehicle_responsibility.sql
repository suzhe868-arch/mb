-- F05-2: ONLY disposable independently sealed PostgreSQL 16; previous M94 is immutable.
-- M94 chain terminates at 000013; 000014_SG06 is a distinct isolated G branch.
-- This isolated 000015 lane MUST NOT run on an unverified G14 database.
CREATE TABLE public.vehicle_current_responsibilities (
 responsibility_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 vehicle_id BIGINT NOT NULL,
 listing_cycle_id BIGINT NOT NULL,
 responsible_employee_id BIGINT NOT NULL REFERENCES public.employees(employee_id) ON DELETE RESTRICT,
 team_id BIGINT NOT NULL REFERENCES public.teams(team_id) ON DELETE RESTRICT,
 source_snapshot TEXT NOT NULL CHECK(source_snapshot IN ('mingbang','four_s')),
 provenance_kind TEXT NOT NULL CHECK(provenance_kind IN ('AUTHORIZED_MANUAL_PUBLICATION','AUTHORIZED_FORMAL_HANDOVER')),
 trusted_event_key TEXT NOT NULL UNIQUE CHECK(length(trusted_event_key) BETWEEN 20 AND 160),
 issuer_employee_id BIGINT NOT NULL REFERENCES public.employees(employee_id) ON DELETE RESTRICT,
 issued_at TIMESTAMPTZ NOT NULL DEFAULT transaction_timestamp(),
 revoked_at TIMESTAMPTZ,
 version BIGINT NOT NULL DEFAULT 1 CHECK(version>0),
 CHECK(revoked_at IS NULL OR revoked_at>=issued_at),
 FOREIGN KEY(listing_cycle_id,vehicle_id)
 REFERENCES public.vehicle_listing_cycles(listing_cycle_id,vehicle_id) ON DELETE RESTRICT
);
-- Unique CURRENT PRIMARY steward, NOT unique authorized reader: a manager in scope can still
-- be separately permitted. Existing cycle snapshots remain immutable historical rows.
CREATE UNIQUE INDEX f05_2_current_responsibility_cycle_uniq
 ON public.vehicle_current_responsibilities(vehicle_id,listing_cycle_id) WHERE revoked_at IS NULL;
CREATE INDEX f05_2_current_responsibility_owner_idx
 ON public.vehicle_current_responsibilities(responsible_employee_id,revoked_at);
CREATE TABLE public.vehicle_responsibility_audit_events (
 audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 responsibility_id BIGINT NOT NULL REFERENCES public.vehicle_current_responsibilities(responsibility_id) ON DELETE RESTRICT,
 event_key TEXT NOT NULL UNIQUE CHECK(length(event_key) BETWEEN 20 AND 160),
 event_kind TEXT NOT NULL CHECK(event_kind IN ('ISSUE','REVOKE','TRANSFER')),
 actor_employee_id BIGINT NOT NULL REFERENCES public.employees(employee_id) ON DELETE RESTRICT,
 previous_employee_id BIGINT REFERENCES public.employees(employee_id) ON DELETE RESTRICT,
 current_employee_id BIGINT REFERENCES public.employees(employee_id) ON DELETE RESTRICT,
 source_evidence TEXT NOT NULL CHECK(length(source_evidence)>10),
 happened_at TIMESTAMPTZ NOT NULL DEFAULT transaction_timestamp()
);
CREATE FUNCTION public.f05_2_audit_immutable() RETURNS trigger
 LANGUAGE plpgsql AS $$
 BEGIN
   RAISE EXCEPTION 'F05_2_AUDIT_IMMUTABLE';
 END
 $$;
CREATE TRIGGER f05_2_audit_no_update_delete
 BEFORE UPDATE OR DELETE ON public.vehicle_responsibility_audit_events
 FOR EACH ROW EXECUTE FUNCTION public.f05_2_audit_immutable();
