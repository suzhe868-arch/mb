-- F05-3C additive non-production PostgreSQL16. M94 and 000015-000017 stay frozen.
CREATE TABLE public.f05_3c_wholesale_conversions (
 conversion_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 vehicle_id BIGINT NOT NULL UNIQUE REFERENCES public.vehicles(vehicle_id) ON DELETE RESTRICT,
 listing_cycle_id BIGINT NOT NULL,
 lineage_id BIGINT NOT NULL UNIQUE REFERENCES public.f05_3b_sync_lineages(lineage_id),
 source_platform TEXT NOT NULL CHECK(source_platform='JYT'),
 car_code TEXT NOT NULL,
 actor_employee_id BIGINT NOT NULL REFERENCES public.employees(employee_id),
 actor_team_id BIGINT NOT NULL REFERENCES public.teams(team_id),
 event_key TEXT NOT NULL UNIQUE CHECK(length(event_key) BETWEEN 20 AND 160),
 before_state JSONB NOT NULL CHECK(jsonb_typeof(before_state)='object'),
 after_state JSONB NOT NULL CHECK(jsonb_typeof(after_state)='object'),
 source_evidence JSONB NOT NULL CHECK(jsonb_typeof(source_evidence)='object'),
 asset_state TEXT NOT NULL DEFAULT 'IMAGE_LOCALIZATION_SOURCE_GAP'
   CHECK(asset_state='IMAGE_LOCALIZATION_SOURCE_GAP'),
 converted_at TIMESTAMPTZ NOT NULL DEFAULT transaction_timestamp(),
 transaction_id BIGINT NOT NULL CHECK(transaction_id>0),
 FOREIGN KEY(listing_cycle_id,vehicle_id)
  REFERENCES public.vehicle_listing_cycles(listing_cycle_id,vehicle_id) ON DELETE RESTRICT,
 UNIQUE(vehicle_id,listing_cycle_id),
 UNIQUE(source_platform,car_code)
);
CREATE TABLE public.f05_3c_conversion_audit (
 audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 conversion_id BIGINT NOT NULL REFERENCES public.f05_3c_wholesale_conversions(conversion_id),
 actor_kind TEXT NOT NULL CHECK(actor_kind='EMPLOYEE'),
 actor_employee_id BIGINT NOT NULL REFERENCES public.employees(employee_id),
 event_key TEXT NOT NULL UNIQUE,
 before_state JSONB NOT NULL CHECK(jsonb_typeof(before_state)='object'),
 after_state JSONB NOT NULL CHECK(jsonb_typeof(after_state)='object'),
 txid BIGINT NOT NULL CHECK(txid>0),
 happened_at TIMESTAMPTZ NOT NULL DEFAULT transaction_timestamp()
);
CREATE FUNCTION public.f05_3c_immutable() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 RAISE EXCEPTION 'F05_3C_SIGNED_HISTORY_IMMUTABLE';
END $$;
CREATE TRIGGER f05_3c_conversion_immutable BEFORE UPDATE OR DELETE ON public.f05_3c_wholesale_conversions
FOR EACH ROW EXECUTE FUNCTION public.f05_3c_immutable();
CREATE TRIGGER f05_3c_audit_immutable BEFORE UPDATE OR DELETE ON public.f05_3c_conversion_audit
FOR EACH ROW EXECUTE FUNCTION public.f05_3c_immutable();
-- Once a vehicle was converted it is not permitted to return to wholesale, even
-- by using a raw SQL statement outside the isolated handler.
CREATE FUNCTION public.f05_3c_source_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.source_type='wholesale' AND OLD.source_type<>'wholesale'
 AND EXISTS(SELECT 1 FROM public.f05_3c_wholesale_conversions c
            WHERE c.vehicle_id=NEW.vehicle_id) THEN
  RAISE EXCEPTION 'F05_3C_WHOLESALE_SOURCE_REVERSAL_FORBIDDEN';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER f05_3c_vehicle_source_guard BEFORE UPDATE OF source_type ON public.vehicles
FOR EACH ROW EXECUTE FUNCTION public.f05_3c_source_guard();
