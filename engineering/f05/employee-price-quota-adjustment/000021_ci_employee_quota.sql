CREATE TABLE public.f05_5_quota_addition_events_ci (
 event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 idempotency_key TEXT NOT NULL UNIQUE CHECK(length(idempotency_key) BETWEEN 20 AND 160),
 customer_id BIGINT NOT NULL REFERENCES public.customers(customer_id) ON DELETE RESTRICT,
 actor_employee_id BIGINT NOT NULL REFERENCES public.employees(employee_id) ON DELETE RESTRICT,
 adjustment_id BIGINT NOT NULL UNIQUE REFERENCES public.customer_quota_adjustments(adjustment_id) ON DELETE RESTRICT,
 business_day_shanghai DATE NOT NULL,
 added_count INTEGER NOT NULL CHECK(added_count BETWEEN 1 AND 100),
 before_temp_additions INTEGER NOT NULL CHECK(before_temp_additions>=0),
 after_temp_additions INTEGER NOT NULL CHECK(after_temp_additions=before_temp_additions+added_count),
 current_owner_at_commit BIGINT NOT NULL REFERENCES public.employees(employee_id) ON DELETE RESTRICT,
 actor_role_at_commit TEXT NOT NULL CHECK(actor_role_at_commit IN ('sales','manager','store_head')),
 actor_scope_team_id BIGINT NOT NULL REFERENCES public.teams(team_id),
 synthetic_fixture_only TEXT NOT NULL CHECK(synthetic_fixture_only='CI_SYNTHETIC_ROLE_FIXTURE_NOT_PRODUCTION'),
 txid BIGINT NOT NULL CHECK(txid>0),
 occurred_at TIMESTAMPTZ NOT NULL DEFAULT transaction_timestamp()
);
CREATE FUNCTION public.f05_5_forbid_event_mutation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'F05_5_QUOTA_EVENT_IMMUTABLE' USING ERRCODE='23514'; END $$;
CREATE TRIGGER f05_5_quota_event_immutable BEFORE UPDATE OR DELETE
 ON public.f05_5_quota_addition_events_ci FOR EACH ROW EXECUTE FUNCTION public.f05_5_forbid_event_mutation();
CREATE TABLE public.f05_5_migration_attestation(
 seal_key TEXT PRIMARY KEY CHECK(seal_key='M94_TO_V20_SIGNED_LEDGER'),
 preceding_records_sha256 TEXT NOT NULL CHECK(preceding_records_sha256 ~ '^[0-9a-f]{64}$'),
 prior_checksum_sha256 TEXT NOT NULL CHECK(prior_checksum_sha256 ~ '^[0-9a-f]{64}$'),
 prior_structure_sha256 TEXT NOT NULL CHECK(prior_structure_sha256 ~ '^[0-9a-f]{64}$')
);
CREATE TRIGGER f05_5_attestation_immutable BEFORE UPDATE OR DELETE
 ON public.f05_5_migration_attestation FOR EACH ROW EXECUTE FUNCTION public.f05_5_forbid_event_mutation();
REVOKE ALL ON public.f05_5_quota_addition_events_ci FROM PUBLIC;
REVOKE ALL ON public.f05_5_migration_attestation FROM PUBLIC;
