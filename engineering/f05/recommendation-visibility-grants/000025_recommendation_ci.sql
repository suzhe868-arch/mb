-- Existing M94 Grant has no cycle column. Legal cycle/active relationship is
-- ALWAYS resolved by joining its source Recommendation, never by vehicle ID.
CREATE FUNCTION public.f05_9_sync_hidden_grants_ci() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE one_rec RECORD;
BEGIN
 IF NEW.platform_visibility IS DISTINCT FROM OLD.platform_visibility
 AND NEW.platform_visibility='hidden' THEN
  FOR one_rec IN
   SELECT r.recommendation_id,r.customer_id FROM public.recommendations r
   JOIN public.vehicle_listing_cycles lc ON lc.listing_cycle_id=r.listing_cycle_id
   WHERE r.vehicle_id=NEW.vehicle_id AND r.status='active'
   AND lc.vehicle_id=r.vehicle_id AND lc.ended_at IS NULL
  LOOP
   -- Original source_recommendation_id is an immutable business source.
   -- A previously revoked grant is not reused; the cycle-scoped projection
   -- still denies old ended Recommendations.
   IF NOT EXISTS(SELECT 1 FROM public.vehicle_visibility_grants g
       WHERE g.source_recommendation_id=one_rec.recommendation_id
       AND g.revoked_at IS NULL) THEN
    INSERT INTO public.vehicle_visibility_grants(vehicle_id,customer_id,source_recommendation_id)
     VALUES(NEW.vehicle_id,one_rec.customer_id,one_rec.recommendation_id);
   END IF;
  END LOOP;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER f05_9_hidden_change_ci AFTER UPDATE OF platform_visibility ON public.vehicles
 FOR EACH ROW EXECUTE FUNCTION public.f05_9_sync_hidden_grants_ci();
