-- F05-6 CI-ONLY additive M94->v21->v22; no production Application/Demand Issuer.
CREATE TABLE public.f05_6_level_find_policy_ci (
 level_id BIGINT PRIMARY KEY REFERENCES public.customer_levels(level_id),
 find_enabled BOOLEAN NOT NULL,
 source_marker TEXT NOT NULL DEFAULT 'CI_SYNTHETIC_FIND_CAR_ENTITLEMENT_NOT_PRODUCTION'
 CHECK (source_marker='CI_SYNTHETIC_FIND_CAR_ENTITLEMENT_NOT_PRODUCTION')
);
CREATE TABLE public.f05_6_application_origin_ci (
 application_id BIGINT PRIMARY KEY REFERENCES public.find_car_applications(application_id) ON DELETE RESTRICT,
 customer_id BIGINT NOT NULL REFERENCES public.customers(customer_id),
 assigned_employee_id BIGINT NOT NULL REFERENCES public.employees(employee_id),
 application_key TEXT NOT NULL UNIQUE CHECK(length(application_key) BETWEEN 20 AND 160),
 desired_vehicle TEXT NOT NULL CHECK(length(trim(desired_vehicle)) BETWEEN 2 AND 256),
 content_revision INTEGER NOT NULL DEFAULT 1 CHECK(content_revision>=1),
 phone_gate_marker TEXT NOT NULL CHECK(phone_gate_marker='CI_SYNTHETIC_PHONE_GATE_NOT_PRODUCTION'),
 customer_actor_marker TEXT NOT NULL CHECK(customer_actor_marker='CI_SYNTHETIC_CUSTOMER_ACTOR_NOT_PRODUCTION'),
 entered_at TIMESTAMPTZ NOT NULL DEFAULT transaction_timestamp(),
 UNIQUE(application_id,customer_id,assigned_employee_id),
 UNIQUE(application_id,customer_id)
);
CREATE TABLE public.f05_6_activation_events_ci (
 event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 application_id BIGINT NOT NULL UNIQUE REFERENCES public.find_car_applications(application_id),
 demand_id BIGINT NOT NULL UNIQUE REFERENCES public.demands(demand_id),
 customer_id BIGINT NOT NULL REFERENCES public.customers(customer_id),
 actor_employee_id BIGINT NOT NULL REFERENCES public.employees(employee_id),
 request_key TEXT NOT NULL UNIQUE CHECK(length(request_key) BETWEEN 20 AND 160),
 demand_created_at TIMESTAMPTZ NOT NULL,
 original_application_owner BIGINT NOT NULL REFERENCES public.employees(employee_id),
 synthetic_issuer TEXT NOT NULL CHECK(synthetic_issuer='CI_SYNTHETIC_DEMAND_ACTIVATION_PERMISSION_NOT_PRODUCTION'),
 occurred_at TIMESTAMPTZ NOT NULL DEFAULT transaction_timestamp(),
 txid BIGINT NOT NULL CHECK(txid>0),
 FOREIGN KEY(application_id,customer_id) REFERENCES public.f05_6_application_origin_ci(application_id,customer_id)
);
CREATE TABLE public.f05_6_migration_attestation(
 seal_key TEXT PRIMARY KEY CHECK(seal_key='M94_TO_V21_SIGNED_LEDGER'),
 preceding_records_sha256 TEXT NOT NULL CHECK(preceding_records_sha256 ~ '^[0-9a-f]{64}$'),
 prior_checksum_sha256 TEXT NOT NULL CHECK(prior_checksum_sha256 ~ '^[0-9a-f]{64}$'),
 prior_structure_sha256 TEXT NOT NULL CHECK(prior_structure_sha256 ~ '^[0-9a-f]{64}$')
);
CREATE FUNCTION public.f05_6_immutable_event() RETURNS trigger LANGUAGE plpgsql AS $$
 BEGIN RAISE EXCEPTION 'F05_6_SIGNED_APPLICATION_DEMAND_FACT_IMMUTABLE' USING ERRCODE='23514'; END $$;
CREATE TRIGGER f05_6_activation_append_only BEFORE UPDATE OR DELETE ON public.f05_6_activation_events_ci
 FOR EACH ROW EXECUTE FUNCTION public.f05_6_immutable_event();
CREATE TRIGGER f05_6_attestation_append_only BEFORE UPDATE OR DELETE ON public.f05_6_migration_attestation
 FOR EACH ROW EXECUTE FUNCTION public.f05_6_immutable_event();
CREATE FUNCTION public.f05_6_demand_created_at_frozen() RETURNS trigger LANGUAGE plpgsql AS $$
 BEGIN IF NEW.created_at IS DISTINCT FROM OLD.created_at THEN RAISE EXCEPTION 'F05_6_DEMAND_CREATION_TIME_FROZEN' USING ERRCODE='23514'; END IF; RETURN NEW; END $$;
CREATE TRIGGER f05_6_existing_demand_created_at_frozen BEFORE UPDATE ON public.demands
 FOR EACH ROW EXECUTE FUNCTION public.f05_6_demand_created_at_frozen();
CREATE UNIQUE INDEX f05_6_activated_one_application_per_demand_ci ON public.find_car_applications(activated_demand_id)
 WHERE activated_demand_id IS NOT NULL;
REVOKE ALL ON public.f05_6_level_find_policy_ci,public.f05_6_application_origin_ci,public.f05_6_activation_events_ci,public.f05_6_migration_attestation FROM PUBLIC;
