-- F05-3A disposable PG16 only: 4S individual is represented subject; NO merchant organization.
-- Additional version only. F05-2 000015, M94, its 36 frozen CI jobs remain untouched.
CREATE TABLE public.f05_3a_member_create_licenses(
 license_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 employee_id BIGINT NOT NULL REFERENCES public.employees(employee_id) ON DELETE RESTRICT,
 scope_kind TEXT NOT NULL DEFAULT 'NEW_OWN_FOUR_S_MANUAL_VEHICLE' CHECK(scope_kind='NEW_OWN_FOUR_S_MANUAL_VEHICLE'),
 granted_by_system_admin_id BIGINT NOT NULL REFERENCES public.system_admins(system_admin_id) ON DELETE RESTRICT,
 grant_event_key TEXT NOT NULL UNIQUE CHECK(length(grant_event_key) BETWEEN 20 AND 160),
 granted_at TIMESTAMPTZ NOT NULL DEFAULT transaction_timestamp(),
 revoked_at TIMESTAMPTZ,
 version BIGINT NOT NULL DEFAULT 1 CHECK(version>=1),
 CHECK(revoked_at IS NULL OR revoked_at>=granted_at)
);
CREATE UNIQUE INDEX f05_3a_current_member_create_license
 ON public.f05_3a_member_create_licenses(employee_id) WHERE revoked_at IS NULL;
CREATE TABLE public.f05_3a_member_publications(
 publication_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 vehicle_id BIGINT NOT NULL UNIQUE REFERENCES public.vehicles(vehicle_id) ON DELETE RESTRICT,
 listing_cycle_id BIGINT NOT NULL UNIQUE,
 license_id BIGINT NOT NULL REFERENCES public.f05_3a_member_create_licenses(license_id) ON DELETE RESTRICT,
 member_employee_id BIGINT NOT NULL REFERENCES public.employees(employee_id) ON DELETE RESTRICT,
 trusted_event_key TEXT NOT NULL UNIQUE CHECK(length(trusted_event_key) BETWEEN 20 AND 160),
 source_kind TEXT NOT NULL DEFAULT 'four_s' CHECK(source_kind='four_s'),
 brand_id BIGINT NOT NULL REFERENCES public.vehicle_brands(brand_id) ON DELETE RESTRICT,
 series_id BIGINT NOT NULL REFERENCES public.vehicle_series(series_id) ON DELETE RESTRICT,
 model_id BIGINT NOT NULL REFERENCES public.vehicle_models(model_id) ON DELETE RESTRICT,
 model_year INTEGER NOT NULL CHECK(model_year BETWEEN 1980 AND 2100),
 mileage_km INTEGER NOT NULL CHECK(mileage_km BETWEEN 0 AND 3000000),
 city TEXT NOT NULL CHECK(length(btrim(city)) BETWEEN 2 AND 100),
 published_at TIMESTAMPTZ NOT NULL DEFAULT transaction_timestamp(),
 revoked_at TIMESTAMPTZ,
 version BIGINT NOT NULL DEFAULT 1 CHECK(version>=1),
 FOREIGN KEY(listing_cycle_id,vehicle_id) REFERENCES public.vehicle_listing_cycles(listing_cycle_id,vehicle_id) ON DELETE RESTRICT,
 CHECK(revoked_at IS NULL OR revoked_at>=published_at)
);
CREATE UNIQUE INDEX f05_3a_current_member_vehicle ON public.f05_3a_member_publications(vehicle_id,listing_cycle_id) WHERE revoked_at IS NULL;
CREATE INDEX f05_3a_member_object_scope ON public.f05_3a_member_publications(member_employee_id,revoked_at);
CREATE TABLE public.f05_3a_member_trust_audit(
 audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 event_key TEXT NOT NULL UNIQUE CHECK(length(event_key) BETWEEN 20 AND 160),
 license_id BIGINT REFERENCES public.f05_3a_member_create_licenses(license_id) ON DELETE RESTRICT,
 publication_id BIGINT REFERENCES public.f05_3a_member_publications(publication_id) ON DELETE RESTRICT,
 event_kind TEXT NOT NULL CHECK(event_kind IN('ADMIN_GRANT','ADMIN_REVOKE','MEMBER_PUBLISH','SYSTEM_LICENSE_REVOKE','SYSTEM_OBJECT_REVOKE')),
 actor_kind TEXT NOT NULL CHECK(actor_kind IN('SYSTEM_ADMIN','FOUR_S_MEMBER','SYSTEM')),
 actor_system_admin_id BIGINT REFERENCES public.system_admins(system_admin_id),
 actor_member_employee_id BIGINT REFERENCES public.employees(employee_id),
 affected_employee_id BIGINT NOT NULL REFERENCES public.employees(employee_id),
 actor_context JSONB NOT NULL DEFAULT '{}'::jsonb CHECK(jsonb_typeof(actor_context)='object'),
 before_state JSONB NOT NULL DEFAULT '{}'::jsonb CHECK(jsonb_typeof(before_state)='object'),
 after_state JSONB NOT NULL DEFAULT '{}'::jsonb CHECK(jsonb_typeof(after_state)='object'),
 happened_at TIMESTAMPTZ NOT NULL DEFAULT transaction_timestamp(),
 CHECK(license_id IS NOT NULL OR publication_id IS NOT NULL),
 CHECK((actor_kind='SYSTEM_ADMIN' AND actor_system_admin_id IS NOT NULL AND actor_member_employee_id IS NULL)
 OR(actor_kind='FOUR_S_MEMBER' AND actor_member_employee_id IS NOT NULL AND actor_system_admin_id IS NULL)
 OR(actor_kind='SYSTEM' AND actor_member_employee_id IS NULL AND actor_system_admin_id IS NULL
    AND actor_context->>'trigger'='f05_3a_invalidation'))
);
CREATE FUNCTION public.f05_3a_immutable_audit() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'F05_3A_AUDIT_IMMUTABLE'; END $$;
CREATE TRIGGER f05_3a_audit_no_update_delete BEFORE UPDATE OR DELETE ON public.f05_3a_member_trust_audit
FOR EACH ROW EXECUTE FUNCTION public.f05_3a_immutable_audit();
-- Invalidation is transaction-causal, actor=SYSTEM, NEVER the affected member.
CREATE FUNCTION public.f05_3a_close_member_license(who BIGINT, cause TEXT) RETURNS VOID LANGUAGE plpgsql AS $$
DECLARE x RECORD;
BEGIN
 IF who IS NULL OR who<1 OR who>2147483647 THEN RETURN; END IF;
 PERFORM pg_advisory_xact_lock(20261011,who::integer);
 FOR x IN UPDATE public.f05_3a_member_create_licenses SET revoked_at=transaction_timestamp(),version=version+1
  WHERE employee_id=who AND revoked_at IS NULL RETURNING license_id,employee_id,version,revoked_at LOOP
  INSERT INTO public.f05_3a_member_trust_audit(event_key,license_id,event_kind,actor_kind,affected_employee_id,actor_context,before_state,after_state)
  VALUES('auto:license:'||x.license_id||':'||txid_current()||':'||cause,x.license_id,
   'SYSTEM_LICENSE_REVOKE','SYSTEM',x.employee_id,
   jsonb_build_object('trigger','f05_3a_invalidation','cause',cause,'txid',txid_current()),
   jsonb_build_object('active',true,'version',x.version-1),
   jsonb_build_object('active',false,'version',x.version,'revoked_at',x.revoked_at));
 END LOOP;
END $$;
CREATE FUNCTION public.f05_3a_license_revocation_cascade() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE x RECORD;
BEGIN
 IF NEW.revoked_at IS NOT NULL AND OLD.revoked_at IS NULL THEN
  FOR x IN UPDATE public.f05_3a_member_publications SET revoked_at=transaction_timestamp(),version=version+1
   WHERE license_id=NEW.license_id AND revoked_at IS NULL
   RETURNING publication_id,member_employee_id,version,revoked_at LOOP
   INSERT INTO public.f05_3a_member_trust_audit(event_key,license_id,publication_id,event_kind,actor_kind,affected_employee_id,actor_context,before_state,after_state)
   VALUES('auto:object:revoke:'||x.publication_id||':'||txid_current(),NEW.license_id,x.publication_id,
    'SYSTEM_OBJECT_REVOKE','SYSTEM',x.member_employee_id,
    jsonb_build_object('trigger','f05_3a_invalidation','cause','LICENSE_REVOKED','txid',txid_current()),
    jsonb_build_object('active',true,'version',x.version-1),
    jsonb_build_object('active',false,'version',x.version,'revoked_at',x.revoked_at));
  END LOOP;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER f05_3a_cascade_license AFTER UPDATE ON public.f05_3a_member_create_licenses
FOR EACH ROW EXECUTE FUNCTION public.f05_3a_license_revocation_cascade();
CREATE FUNCTION public.f05_3a_invalidate_member() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE who BIGINT; x RECORD;
BEGIN
 IF TG_TABLE_NAME='employees' THEN
  IF TG_OP='UPDATE' AND ROW(NEW.employment_status,NEW.main_role_id,NEW.store_id)
      IS NOT DISTINCT FROM ROW(OLD.employment_status,OLD.main_role_id,OLD.store_id) THEN RETURN NEW; END IF;
  who:=NEW.employee_id;
 ELSIF TG_TABLE_NAME='pc_login_accounts' THEN
  IF TG_OP='UPDATE' AND ROW(NEW.credential_state,NEW.force_password_change,NEW.credential_epoch,NEW.employee_id,NEW.principal_kind)
      IS NOT DISTINCT FROM ROW(OLD.credential_state,OLD.force_password_change,OLD.credential_epoch,OLD.employee_id,OLD.principal_kind) THEN RETURN NEW; END IF;
  who:=COALESCE(NEW.employee_id,OLD.employee_id);
 ELSIF TG_TABLE_NAME='employee_permission_overrides' THEN
  who:=CASE WHEN TG_OP='DELETE' THEN OLD.employee_id ELSE NEW.employee_id END;
  IF NOT EXISTS(SELECT 1 FROM public.permissions WHERE permission_id=COALESCE(NEW.permission_id,OLD.permission_id)
       AND permission_code='pc.four_s.vehicle.manage') THEN
   RETURN CASE WHEN TG_OP='DELETE' THEN OLD ELSE NEW END;
  END IF;
 ELSIF TG_TABLE_NAME='vehicles' THEN
  IF ROW(NEW.source_type,NEW.source_sale_status,NEW.archived_at)
      IS NOT DISTINCT FROM ROW(OLD.source_type,OLD.source_sale_status,OLD.archived_at) THEN RETURN NEW; END IF;
  FOR x IN SELECT DISTINCT p.member_employee_id FROM public.f05_3a_member_publications p
      WHERE p.vehicle_id=NEW.vehicle_id AND p.revoked_at IS NULL LOOP
   PERFORM public.f05_3a_close_member_license(x.member_employee_id,'VEHICLE_CHANGED');
  END LOOP;
  RETURN NEW;
 ELSIF TG_TABLE_NAME='vehicle_listing_cycles' THEN
  IF ROW(NEW.ended_at,NEW.vehicle_id)
      IS NOT DISTINCT FROM ROW(OLD.ended_at,OLD.vehicle_id) THEN RETURN NEW; END IF;
  FOR x IN SELECT DISTINCT p.member_employee_id FROM public.f05_3a_member_publications p
      WHERE p.listing_cycle_id=NEW.listing_cycle_id AND p.revoked_at IS NULL LOOP
   PERFORM public.f05_3a_close_member_license(x.member_employee_id,'CYCLE_CHANGED');
  END LOOP;
  RETURN NEW;
 END IF;
 PERFORM public.f05_3a_close_member_license(who,'GOVERNANCE_'||TG_TABLE_NAME);
 RETURN CASE WHEN TG_OP='DELETE' THEN OLD ELSE NEW END;
END $$;
CREATE TRIGGER f05_3a_employee_eligibility AFTER UPDATE ON public.employees
FOR EACH ROW EXECUTE FUNCTION public.f05_3a_invalidate_member();
CREATE TRIGGER f05_3a_account_eligibility AFTER UPDATE ON public.pc_login_accounts
FOR EACH ROW EXECUTE FUNCTION public.f05_3a_invalidate_member();
CREATE TRIGGER f05_3a_permission_eligibility AFTER INSERT OR UPDATE OR DELETE ON public.employee_permission_overrides
FOR EACH ROW EXECUTE FUNCTION public.f05_3a_invalidate_member();
CREATE TRIGGER f05_3a_vehicle_lifecycle AFTER UPDATE ON public.vehicles
FOR EACH ROW EXECUTE FUNCTION public.f05_3a_invalidate_member();
CREATE TRIGGER f05_3a_listing_lifecycle AFTER UPDATE ON public.vehicle_listing_cycles
FOR EACH ROW EXECUTE FUNCTION public.f05_3a_invalidate_member();
