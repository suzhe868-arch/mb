-- F05 manual vehicle draft/publish: disposable PG16 private-schema sidecar only.
-- Never alters the frozen public schema or the 000001..000016 migration history.
CREATE SCHEMA f05_manual_vehicle_test;
CREATE TABLE f05_manual_vehicle_test.schema_state (
 singleton BOOLEAN PRIMARY KEY DEFAULT TRUE CHECK (singleton),
 version INTEGER NOT NULL CHECK (version = 1),
 run_id TEXT NOT NULL CHECK (length(run_id) BETWEEN 1 AND 40),
 ddl_sha256 TEXT NOT NULL CHECK (ddl_sha256 ~ '^[0-9a-f]{64}$'),
 applied_at TIMESTAMPTZ NOT NULL DEFAULT transaction_timestamp()
);
CREATE TABLE f05_manual_vehicle_test.drafts (
 draft_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 created_by_employee_id BIGINT NOT NULL REFERENCES public.employees(employee_id) ON DELETE RESTRICT,
 draft_source_type TEXT NOT NULL CHECK (draft_source_type IN ('mingbang','four_s')),
 source_team_id BIGINT REFERENCES public.teams(team_id) ON DELETE RESTRICT,
 draft_payload JSONB NOT NULL CHECK (jsonb_typeof(draft_payload)='object'),
 status TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','published')),
 version BIGINT NOT NULL DEFAULT 1 CHECK (version > 0),
 reserved_vehicle_id BIGINT UNIQUE,
 reserved_listing_cycle_id BIGINT UNIQUE,
 published_vehicle_id BIGINT UNIQUE REFERENCES public.vehicles(vehicle_id) ON DELETE RESTRICT,
 published_listing_cycle_id BIGINT,
 created_at TIMESTAMPTZ NOT NULL DEFAULT transaction_timestamp(),
 first_meaningful_at TIMESTAMPTZ NOT NULL DEFAULT transaction_timestamp(),
 last_autosaved_at TIMESTAMPTZ NOT NULL DEFAULT transaction_timestamp(),
 published_at TIMESTAMPTZ,
 FOREIGN KEY (published_listing_cycle_id,published_vehicle_id)
   REFERENCES public.vehicle_listing_cycles(listing_cycle_id,vehicle_id) ON DELETE RESTRICT,
 CHECK (
   (status='draft' AND published_vehicle_id IS NULL AND published_listing_cycle_id IS NULL AND published_at IS NULL)
   OR
   (status='published' AND published_vehicle_id IS NOT NULL AND published_listing_cycle_id IS NOT NULL AND published_at IS NOT NULL)
 )
);
CREATE INDEX f05_manual_drafts_owner_status_idx
 ON f05_manual_vehicle_test.drafts(created_by_employee_id,status,last_autosaved_at DESC,draft_id DESC);
CREATE INDEX f05_manual_drafts_team_idx
 ON f05_manual_vehicle_test.drafts(source_team_id,created_by_employee_id,status);
CREATE TABLE f05_manual_vehicle_test.draft_events (
 event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 event_key TEXT NOT NULL UNIQUE CHECK (length(event_key) BETWEEN 20 AND 160),
 draft_id BIGINT NOT NULL CHECK (draft_id > 0),
 actor_employee_id BIGINT NOT NULL REFERENCES public.employees(employee_id) ON DELETE RESTRICT,
 draft_source_type TEXT NOT NULL CHECK (draft_source_type IN ('mingbang','four_s')),
 event_kind TEXT NOT NULL CHECK (event_kind IN ('CREATED','AUTOSAVED','PUBLISHED','DELETED')),
 payload_sha256 TEXT CHECK (payload_sha256 IS NULL OR payload_sha256 ~ '^[0-9a-f]{64}$'),
 event_metadata JSONB NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(event_metadata)='object'),
 occurred_at TIMESTAMPTZ NOT NULL DEFAULT transaction_timestamp()
);
CREATE FUNCTION f05_manual_vehicle_test.reject_audit_mutation() RETURNS trigger
 LANGUAGE plpgsql AS $$
 BEGIN
   RAISE EXCEPTION 'F05_MANUAL_DRAFT_AUDIT_IMMUTABLE';
 END
 $$;
CREATE TRIGGER f05_manual_draft_events_immutable
 BEFORE UPDATE OR DELETE ON f05_manual_vehicle_test.draft_events
 FOR EACH ROW EXECUTE FUNCTION f05_manual_vehicle_test.reject_audit_mutation();
CREATE TABLE f05_manual_vehicle_test.published_vehicle_facts (
 vehicle_id BIGINT PRIMARY KEY REFERENCES public.vehicles(vehicle_id) ON DELETE RESTRICT,
 listing_cycle_id BIGINT NOT NULL UNIQUE,
 source_type TEXT NOT NULL CHECK (source_type IN ('mingbang','four_s')),
 created_by_employee_id BIGINT NOT NULL REFERENCES public.employees(employee_id) ON DELETE RESTRICT,
 brand_id BIGINT NOT NULL REFERENCES public.vehicle_brands(brand_id) ON DELETE RESTRICT,
 series_id BIGINT NOT NULL REFERENCES public.vehicle_series(series_id) ON DELETE RESTRICT,
 model_id BIGINT NOT NULL REFERENCES public.vehicle_models(model_id) ON DELETE RESTRICT,
 model_year INTEGER NOT NULL CHECK (model_year BETWEEN 1980 AND 2100),
 mileage_km INTEGER NOT NULL CHECK (mileage_km BETWEEN 0 AND 3000000),
 city TEXT NOT NULL CHECK (length(btrim(city)) BETWEEN 2 AND 100),
 payload_snapshot JSONB NOT NULL CHECK (jsonb_typeof(payload_snapshot)='object'),
 published_at TIMESTAMPTZ NOT NULL DEFAULT transaction_timestamp(),
 FOREIGN KEY (listing_cycle_id,vehicle_id)
   REFERENCES public.vehicle_listing_cycles(listing_cycle_id,vehicle_id) ON DELETE RESTRICT
);
REVOKE ALL ON SCHEMA f05_manual_vehicle_test FROM PUBLIC;
REVOKE ALL ON ALL TABLES IN SCHEMA f05_manual_vehicle_test FROM PUBLIC;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA f05_manual_vehicle_test FROM PUBLIC;
REVOKE ALL ON ALL FUNCTIONS IN SCHEMA f05_manual_vehicle_test FROM PUBLIC;
