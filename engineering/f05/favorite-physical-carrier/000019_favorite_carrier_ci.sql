-- F05-3G, additive CI-only 000019. Historical M94 and 000015..000018 stay unchanged.
-- The Favorite relation is CUSTOMER + VEHICLE, intentionally NOT tied to a listing cycle.
CREATE TABLE public.f05_3g_customer_favorites (
 favorite_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 customer_id BIGINT NOT NULL REFERENCES public.customers(customer_id) ON DELETE RESTRICT,
 vehicle_id BIGINT NOT NULL REFERENCES public.vehicles(vehicle_id) ON DELETE RESTRICT,
 current_state TEXT NOT NULL CHECK(current_state IN ('active','removed')),
 state_version BIGINT NOT NULL DEFAULT 1 CHECK(state_version>0),
 created_at TIMESTAMPTZ NOT NULL DEFAULT transaction_timestamp(),
 changed_at TIMESTAMPTZ NOT NULL DEFAULT transaction_timestamp(),
 UNIQUE(customer_id,vehicle_id),
 UNIQUE(favorite_id,customer_id,vehicle_id),
 CHECK(changed_at>=created_at)
);
CREATE TABLE public.f05_3g_favorite_events (
 event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 favorite_id BIGINT NOT NULL,
 customer_id BIGINT NOT NULL,
 vehicle_id BIGINT NOT NULL,
 event_key TEXT NOT NULL UNIQUE CHECK(length(event_key) BETWEEN 20 AND 160),
 payload_sha256 TEXT NOT NULL CHECK(payload_sha256 ~ '^[0-9a-f]{64}$'),
 action TEXT NOT NULL CHECK(action IN ('ADD','REMOVE')),
 outcome TEXT NOT NULL CHECK(outcome IN ('APPLIED','NOOP')),
 before_state TEXT NOT NULL CHECK(before_state IN ('absent','active','removed')),
 after_state TEXT NOT NULL CHECK(after_state IN ('active','removed')),
 actor_kind TEXT NOT NULL CHECK(actor_kind='SYNTHETIC_CUSTOMER_CONTEXT_CI_ONLY'),
 actor_context JSONB NOT NULL CHECK(jsonb_typeof(actor_context)='object'),
 happened_at TIMESTAMPTZ NOT NULL DEFAULT transaction_timestamp(),
 transaction_id BIGINT NOT NULL CHECK(transaction_id>0),
 FOREIGN KEY(favorite_id,customer_id,vehicle_id)
  REFERENCES public.f05_3g_customer_favorites(favorite_id,customer_id,vehicle_id)
  ON DELETE RESTRICT,
 CHECK((outcome='NOOP' AND before_state=after_state) OR
       (outcome='APPLIED' AND before_state<>after_state)),
 CHECK((action='ADD' AND after_state='active') OR
       (action='REMOVE' AND after_state='removed'))
);
CREATE INDEX f05_3g_favorite_history_by_target
 ON public.f05_3g_favorite_events(customer_id,vehicle_id,event_id);
CREATE FUNCTION public.f05_3g_append_only() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'F05_3G_FAVORITE_EVENT_IMMUTABLE'; END $$;
CREATE TRIGGER f05_3g_history_immutable BEFORE UPDATE OR DELETE
 ON public.f05_3g_favorite_events FOR EACH ROW
 EXECUTE FUNCTION public.f05_3g_append_only();
CREATE FUNCTION public.f05_3g_no_rekey_or_delete() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF TG_OP='DELETE' THEN RAISE EXCEPTION 'F05_3G_CURRENT_RELATION_DELETE_DENIED'; END IF;
 IF ROW(NEW.favorite_id,NEW.customer_id,NEW.vehicle_id,NEW.created_at)
    IS DISTINCT FROM ROW(OLD.favorite_id,OLD.customer_id,OLD.vehicle_id,OLD.created_at)
 THEN RAISE EXCEPTION 'F05_3G_CURRENT_IDENTITY_IMMUTABLE'; END IF;
 IF NEW.state_version<>OLD.state_version+1 OR NEW.changed_at<OLD.changed_at
 THEN RAISE EXCEPTION 'F05_3G_CURRENT_VERSION_DENIED'; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER f05_3g_current_guard BEFORE UPDATE OR DELETE
 ON public.f05_3g_customer_favorites FOR EACH ROW
 EXECUTE FUNCTION public.f05_3g_no_rekey_or_delete();
