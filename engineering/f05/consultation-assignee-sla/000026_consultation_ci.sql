CREATE FUNCTION public.f05_10_guard_origin_ci() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF (OLD.source_kind,OLD.source_recommendation_id,OLD.source_demand_id,OLD.customer_id,OLD.vehicle_id,OLD.listing_cycle_id,OLD.origin_team_id,OLD.origin_store_id,OLD.opened_at,OLD.sla_policy_version,OLD.sla_seconds,OLD.original_deadline,OLD.synthetic_source)
 IS DISTINCT FROM
 (NEW.source_kind,NEW.source_recommendation_id,NEW.source_demand_id,NEW.customer_id,NEW.vehicle_id,NEW.listing_cycle_id,NEW.origin_team_id,NEW.origin_store_id,NEW.opened_at,NEW.sla_policy_version,NEW.sla_seconds,NEW.original_deadline,NEW.synthetic_source)
 OR (OLD.first_response_at IS NOT NULL AND NEW.first_response_at IS DISTINCT FROM OLD.first_response_at)
 THEN RAISE EXCEPTION 'F05_10_IMMUTABLE_SOURCE_SLA' USING ERRCODE='23514';END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER f05_10_origin_guard BEFORE UPDATE OR DELETE ON public.f05_10_consultation_meta_ci FOR EACH ROW EXECUTE FUNCTION public.f05_10_guard_origin_ci();
CREATE FUNCTION public.f05_10_consultation_state_guard_ci() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF EXISTS(SELECT 1 FROM public.f05_10_consultation_meta_ci WHERE consultation_id=OLD.consultation_id) THEN
  IF (OLD.customer_id,OLD.vehicle_id,OLD.listing_cycle_id,OLD.source_relation) IS DISTINCT FROM
     (NEW.customer_id,NEW.vehicle_id,NEW.listing_cycle_id,NEW.source_relation)
     OR NEW.assignee_employee_id IS NULL
  THEN RAISE EXCEPTION 'F05_10_IMMUTABLE_ORIGINAL_CONSULTATION' USING ERRCODE='23514'; END IF;
  IF OLD.status IN('resolved','invalid') AND NEW.status IS DISTINCT FROM OLD.status
  THEN RAISE EXCEPTION 'F05_10_TERMINAL_NO_REVIVE' USING ERRCODE='23514';END IF;
  IF NEW.status='resolved' AND NEW.close_reason NOT IN('RESOLVED','NORMAL_CLOSED','CUSTOMER_WITHDRAWN')
  THEN RAISE EXCEPTION 'F05_10_CLOSE_REASON_REQUIRED' USING ERRCODE='23514';END IF;
  IF NEW.status IN('pending','processing') AND (NEW.completed_at IS NOT NULL OR NEW.close_reason IS NOT NULL)
  THEN RAISE EXCEPTION 'F05_10_OPEN_CANNOT_BE_CLOSED' USING ERRCODE='23514';END IF;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER f05_10_consultation_guard BEFORE UPDATE OR DELETE ON public.consultations FOR EACH ROW EXECUTE FUNCTION public.f05_10_consultation_state_guard_ci();
CREATE FUNCTION public.f05_10_customer_disable_hold_ci() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF OLD.account_status='active' AND NEW.account_status IS DISTINCT FROM 'active' THEN
   UPDATE public.f05_10_consultation_meta_ci m SET customer_disabled_hold=TRUE,hold_at=transaction_timestamp(),
      remaining_ms=CASE WHEN m.first_response_at IS NULL THEN
        GREATEST(0,FLOOR(EXTRACT(EPOCH FROM(c.first_response_deadline-transaction_timestamp()))*1000)::BIGINT)
        ELSE m.remaining_ms END
   FROM public.consultations c WHERE c.consultation_id=m.consultation_id
      AND c.customer_id=NEW.customer_id AND c.status IN('pending','processing') AND NOT m.customer_disabled_hold;
   INSERT INTO public.f05_10_consultation_events_ci(consultation_id,event_key,event_kind,actor_kind,actor_id)
   SELECT m.consultation_id,'f05-10-hold-disabled-'||m.consultation_id||'-'||txid_current()::text,
     'hold','system',NEW.customer_id FROM public.f05_10_consultation_meta_ci m
   JOIN public.consultations c ON c.consultation_id=m.consultation_id WHERE c.customer_id=NEW.customer_id
      AND c.status IN('pending','processing') AND m.customer_disabled_hold
   ON CONFLICT(event_key) DO NOTHING;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER f05_10_customer_hold AFTER UPDATE OF account_status ON public.customers FOR EACH ROW EXECUTE FUNCTION public.f05_10_customer_disable_hold_ci();
-- Compute effective current assignee access from actual signed employee/permission/scope facts.
-- Trigger checks run in the same source transaction: after COMMIT the pending Guard is visible.
CREATE FUNCTION public.f05_10_assignee_valid_ci(p_consultation_id BIGINT,p_employee_id BIGINT)
RETURNS BOOLEAN LANGUAGE sql VOLATILE AS $$
 SELECT EXISTS(
  SELECT 1 FROM public.f05_10_consultation_meta_ci m
  JOIN public.employees e ON e.employee_id=p_employee_id AND e.employment_status='active'
  JOIN public.roles r ON r.role_id=e.main_role_id AND r.role_code IN('sales','manager','store_head')
  JOIN public.permissions p ON p.permission_code='consultation.ci.work'
  JOIN public.employee_permission_overrides ov ON ov.employee_id=e.employee_id
   AND ov.permission_id=p.permission_id AND ov.decision='allow'
  JOIN public.employee_capability_scope_bindings b ON b.employee_id=e.employee_id
   AND b.permission_id=p.permission_id AND b.granted_at<=statement_timestamp()
   AND (b.ended_at IS NULL OR b.ended_at>statement_timestamp())
  JOIN public.employee_data_scopes sc ON sc.scope_id=b.scope_id AND sc.employee_id=e.employee_id
   AND (sc.ended_at IS NULL OR sc.ended_at>statement_timestamp())
  WHERE m.consultation_id=p_consultation_id
   AND ((sc.scope_kind='team' AND sc.scope_reference_id=m.origin_team_id)
    OR (sc.scope_kind='store' AND sc.scope_reference_id=m.origin_store_id
      AND r.role_code IN('manager','store_head')))
   AND (r.role_code<>'sales' OR (
     e.store_id=m.origin_store_id AND EXISTS (
       SELECT 1 FROM public.employee_team_memberships tm
       WHERE tm.employee_id=e.employee_id AND tm.team_id=m.origin_team_id
       AND tm.valid_from<=statement_timestamp()
       AND (tm.ended_at IS NULL OR tm.ended_at>statement_timestamp())
     )))
 );
$$;
CREATE FUNCTION public.f05_10_reconcile_assignee_ci(p_employee_id BIGINT,p_origin TEXT)
RETURNS INTEGER LANGUAGE plpgsql AS $$
DECLARE changed INTEGER;
BEGIN
 WITH affected AS (
  UPDATE public.f05_10_consultation_meta_ci m
  SET assignee_handover_pending=TRUE
  FROM public.consultations co
  WHERE co.consultation_id=m.consultation_id AND co.assignee_employee_id=p_employee_id
   AND co.status IN('pending','processing') AND NOT m.assignee_handover_pending
   AND NOT public.f05_10_assignee_valid_ci(co.consultation_id,p_employee_id)
  RETURNING m.consultation_id
 ), events AS (
  INSERT INTO public.f05_10_consultation_events_ci
    (consultation_id,event_key,event_kind,actor_kind,actor_id,facts_json)
  SELECT consultation_id,'f05-10-auto-guard-'||consultation_id||'-'||txid_current()::text,
    'assignee_invalid','system',p_employee_id,jsonb_build_object('source',p_origin)
  FROM affected ON CONFLICT(event_key) DO NOTHING RETURNING event_id
 )
 SELECT count(*) INTO changed FROM events;
 RETURN changed;
END $$;
CREATE FUNCTION public.f05_10_employee_source_revoke_ci() RETURNS trigger LANGUAGE plpgsql AS $
DECLARE subject BIGINT;
BEGIN
 subject=CASE WHEN TG_OP='DELETE' THEN OLD.employee_id ELSE NEW.employee_id END;
 IF TG_OP='DELETE' THEN
  PERFORM public.f05_10_reconcile_assignee_ci(subject,'source_fact_deleted');
  RETURN OLD;
 END IF;
 IF TG_TABLE_NAME='employees' THEN
  IF (OLD.employment_status,OLD.main_role_id) IS DISTINCT FROM (NEW.employment_status,NEW.main_role_id) THEN
   PERFORM public.f05_10_reconcile_assignee_ci(subject,'employee_status_or_role');
  END IF;
 ELSIF TG_TABLE_NAME='employee_permission_overrides' THEN
  IF (OLD.decision,OLD.permission_id) IS DISTINCT FROM (NEW.decision,NEW.permission_id) THEN
   PERFORM public.f05_10_reconcile_assignee_ci(subject,'permission_override');
  END IF;
 ELSIF TG_TABLE_NAME='employee_team_memberships' THEN
  IF (OLD.ended_at,OLD.team_id) IS DISTINCT FROM (NEW.ended_at,NEW.team_id) THEN
   PERFORM public.f05_10_reconcile_assignee_ci(subject,'team_membership');
  END IF;
 ELSIF TG_TABLE_NAME='employee_data_scopes' THEN
  IF (OLD.ended_at,OLD.scope_reference_id,OLD.scope_kind)
   IS DISTINCT FROM (NEW.ended_at,NEW.scope_reference_id,NEW.scope_kind) THEN
   PERFORM public.f05_10_reconcile_assignee_ci(subject,'data_scope');
  END IF;
 ELSE
  IF (OLD.ended_at,OLD.scope_id,OLD.permission_id)
   IS DISTINCT FROM (NEW.ended_at,NEW.scope_id,NEW.permission_id) THEN
   PERFORM public.f05_10_reconcile_assignee_ci(subject,'capability_scope');
  END IF;
 END IF;
 RETURN NEW;
END $;
