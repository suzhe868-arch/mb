-- F05-10/PDM15: disposable nonprivileged PG16 v26 CI sidecar. NO production issuer.
CREATE TABLE public.f05_10_consultation_policy_ci(
 policy_key TEXT PRIMARY KEY,version INTEGER NOT NULL CHECK(version>0),
 seconds INTEGER NOT NULL CHECK(seconds BETWEEN 1 AND 86400),
 source_kind TEXT NOT NULL CHECK(source_kind='CI_SYNTHETIC_NOT_PRODUCTION')
);
INSERT INTO public.f05_10_consultation_policy_ci VALUES('default',1,900,'CI_SYNTHETIC_NOT_PRODUCTION');
CREATE TABLE public.f05_10_consultation_meta_ci(
 consultation_id BIGINT PRIMARY KEY REFERENCES public.consultations(consultation_id),
 source_kind TEXT NOT NULL CHECK(source_kind IN('recommendation','ordinary_share','search','favorite','other')),
 source_recommendation_id BIGINT REFERENCES public.recommendations(recommendation_id),
 source_demand_id BIGINT REFERENCES public.demands(demand_id),
 customer_id BIGINT NOT NULL REFERENCES public.customers(customer_id),
 vehicle_id BIGINT NOT NULL REFERENCES public.vehicles(vehicle_id),
 listing_cycle_id BIGINT NOT NULL,
 origin_team_id BIGINT NOT NULL REFERENCES public.teams(team_id),
 origin_store_id BIGINT NOT NULL REFERENCES public.stores(store_id),
 opened_at TIMESTAMPTZ NOT NULL DEFAULT transaction_timestamp(),
 sla_policy_version INTEGER NOT NULL,
 sla_seconds INTEGER NOT NULL CHECK(sla_seconds>0),
 original_deadline TIMESTAMPTZ NOT NULL,
 remaining_ms BIGINT NOT NULL CHECK(remaining_ms>=0),
 first_response_at TIMESTAMPTZ,
 first_response_event_id BIGINT,
 customer_disabled_hold BOOLEAN NOT NULL DEFAULT FALSE,
 hold_at TIMESTAMPTZ,
 assignee_handover_pending BOOLEAN NOT NULL DEFAULT FALSE,
 synthetic_source TEXT NOT NULL DEFAULT 'CI_SYNTHETIC_PHONE_CONSENT_NOT_PRODUCTION'
 CHECK(synthetic_source='CI_SYNTHETIC_PHONE_CONSENT_NOT_PRODUCTION'),
 FOREIGN KEY(listing_cycle_id,vehicle_id) REFERENCES public.vehicle_listing_cycles(listing_cycle_id,vehicle_id),
 CHECK((source_kind='recommendation')=(source_recommendation_id IS NOT NULL)),
 CHECK((customer_disabled_hold AND hold_at IS NOT NULL) OR (NOT customer_disabled_hold AND hold_at IS NULL)),
 CHECK(first_response_event_id IS NULL OR first_response_at IS NOT NULL)
);
CREATE UNIQUE INDEX f05_10_one_open_consultation_per_cycle_ci ON public.consultations(customer_id,vehicle_id,listing_cycle_id)
 WHERE status IN('pending','processing');
CREATE TABLE public.f05_10_consultation_events_ci(
 event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 consultation_id BIGINT NOT NULL REFERENCES public.consultations(consultation_id),
 event_key TEXT NOT NULL UNIQUE CHECK(length(event_key) BETWEEN 16 AND 160),
 event_kind TEXT NOT NULL CHECK(event_kind IN('created','touched','started','followup','first_human_response','resolved','invalid','customer_withdrawn','hold','resume','handover','assignee_invalid')),
 actor_kind TEXT NOT NULL CHECK(actor_kind IN('employee','customer','system')),
 actor_id BIGINT NOT NULL,
 evidence_kind TEXT,
 facts_json JSONB NOT NULL DEFAULT '{}'::jsonb,
 at TIMESTAMPTZ NOT NULL DEFAULT transaction_timestamp()
);
-- An auditable disposable CI-only source, not an actual telephone/message issuer.
CREATE TABLE public.f05_10_human_service_evidence_ci(
 evidence_ref TEXT PRIMARY KEY CHECK(length(evidence_ref) BETWEEN 16 AND 120),
 consultation_id BIGINT NOT NULL REFERENCES public.consultations(consultation_id),
 actor_id BIGINT NOT NULL REFERENCES public.employees(employee_id),
 evidence_kind TEXT NOT NULL CHECK(evidence_kind IN('call','message','in_person')),
 synthetic_issuer TEXT NOT NULL DEFAULT 'CI_SIGNED_SYNTHETIC_SERVICE_ONLY'
  CHECK(synthetic_issuer='CI_SIGNED_SYNTHETIC_SERVICE_ONLY'),
 captured_at TIMESTAMPTZ NOT NULL DEFAULT transaction_timestamp(),
 consumed_event_id BIGINT UNIQUE REFERENCES public.f05_10_consultation_events_ci(event_id)
);
CREATE TABLE public.f05_10_consultation_handover_ci(
 handover_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 consultation_id BIGINT NOT NULL REFERENCES public.consultations(consultation_id),
 old_assignee_id BIGINT NOT NULL REFERENCES public.employees(employee_id),
 new_assignee_id BIGINT NOT NULL REFERENCES public.employees(employee_id),
 actor_id BIGINT NOT NULL REFERENCES public.employees(employee_id),
 reason TEXT NOT NULL CHECK(length(reason)>2),
 context_json JSONB NOT NULL DEFAULT '{}'::jsonb,
 event_id BIGINT NOT NULL UNIQUE REFERENCES public.f05_10_consultation_events_ci(event_id),
 transferred_at TIMESTAMPTZ NOT NULL DEFAULT transaction_timestamp(),
 CHECK(old_assignee_id<>new_assignee_id)
);
CREATE TABLE public.f05_10_migration_attestation(
 seal_key TEXT PRIMARY KEY CHECK(seal_key='M94_TO_V25_SIGNED_LEDGER'),
 preceding_records_sha256 TEXT NOT NULL CHECK(preceding_records_sha256 ~ '^[0-9a-f]{64}$'),
 prior_checksum_sha256 TEXT NOT NULL CHECK(prior_checksum_sha256 ~ '^[0-9a-f]{64}$'),
 prior_structure_sha256 TEXT NOT NULL CHECK(prior_structure_sha256 ~ '^[0-9a-f]{64}$')
);
CREATE FUNCTION public.f05_10_immutable_ci() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'F05_10_IMMUTABLE_HISTORY' USING ERRCODE='23514'; END $$;
CREATE TRIGGER f05_10_events_immutable BEFORE UPDATE OR DELETE ON public.f05_10_consultation_events_ci FOR EACH ROW EXECUTE FUNCTION public.f05_10_immutable_ci();
CREATE FUNCTION public.f05_10_human_evidence_guard_ci() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF (OLD.evidence_ref,OLD.consultation_id,OLD.actor_id,OLD.evidence_kind,OLD.synthetic_issuer,OLD.captured_at)
 IS DISTINCT FROM
 (NEW.evidence_ref,NEW.consultation_id,NEW.actor_id,NEW.evidence_kind,NEW.synthetic_issuer,NEW.captured_at)
 OR OLD.consumed_event_id IS NOT NULL OR NEW.consumed_event_id IS NULL
 OR NOT EXISTS(SELECT 1 FROM public.f05_10_consultation_events_ci ev
     WHERE ev.event_id=NEW.consumed_event_id AND ev.consultation_id=OLD.consultation_id
      AND ev.actor_kind='employee' AND ev.actor_id=OLD.actor_id
      AND ev.evidence_kind=OLD.evidence_kind AND ev.event_kind='followup')
 THEN RAISE EXCEPTION 'F05_10_IMMUTABLE_HUMAN_EVIDENCE' USING ERRCODE='23514';END IF;
 RETURN NEW;
END $$;
