-- F05-3B CI-only additive DDL. M94 + 000015 + 000016 remain byte frozen.
-- No production migration, actual JYT secret, employee business authority or converted-vehicle backfill.
CREATE TABLE public.f05_3b_sync_credentials (
 credential_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 secret_sha256 TEXT NOT NULL UNIQUE CHECK(secret_sha256 ~ '^[0-9a-f]{64}$'),
 issue_event_key TEXT NOT NULL UNIQUE CHECK(length(issue_event_key) BETWEEN 20 AND 160),
 issued_by_system_admin_id BIGINT NOT NULL REFERENCES public.system_admins(system_admin_id),
 issued_at TIMESTAMPTZ NOT NULL DEFAULT transaction_timestamp(),
 revoked_at TIMESTAMPTZ,
 version BIGINT NOT NULL DEFAULT 1 CHECK(version>0),
 CHECK(revoked_at IS NULL OR revoked_at>=issued_at)
);
CREATE TABLE public.f05_3b_api_controls (
 action TEXT PRIMARY KEY CHECK(action IN ('upsert','offline','current')),
 enabled BOOLEAN NOT NULL DEFAULT FALSE,
 version BIGINT NOT NULL DEFAULT 1 CHECK(version>0),
 configured_by_system_admin_id BIGINT REFERENCES public.system_admins(system_admin_id),
 configured_at TIMESTAMPTZ
);
INSERT INTO public.f05_3b_api_controls(action) VALUES('upsert'),('offline'),('current');

CREATE TABLE public.f05_3b_sync_lineages (
 lineage_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 source_platform TEXT NOT NULL DEFAULT 'JYT' CHECK(source_platform='JYT'),
 car_code TEXT NOT NULL CHECK(car_code ~ '^[a-zA-Z0-9_-]{4,96}$'),
 vehicle_id BIGINT NOT NULL UNIQUE REFERENCES public.vehicles(vehicle_id) ON DELETE RESTRICT,
 brand_id BIGINT NOT NULL REFERENCES public.vehicle_brands(brand_id),
 series_id BIGINT NOT NULL REFERENCES public.vehicle_series(series_id),
 model_id BIGINT NOT NULL REFERENCES public.vehicle_models(model_id),
 model_year INTEGER NOT NULL CHECK(model_year BETWEEN 1980 AND 2100),
 current_cycle_id BIGINT NOT NULL,
 first_seen_at TIMESTAMPTZ NOT NULL DEFAULT transaction_timestamp(),
 version BIGINT NOT NULL DEFAULT 1 CHECK(version>0),
 UNIQUE(source_platform,car_code),
 FOREIGN KEY(current_cycle_id,vehicle_id)
  REFERENCES public.vehicle_listing_cycles(listing_cycle_id,vehicle_id) ON DELETE RESTRICT
);
CREATE INDEX f05_3b_sync_vehicle_status ON public.f05_3b_sync_lineages(vehicle_id,current_cycle_id);

