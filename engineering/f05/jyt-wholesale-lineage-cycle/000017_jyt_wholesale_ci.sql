CREATE FUNCTION public.f05_3b_credential_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF TG_OP='DELETE' THEN RAISE EXCEPTION 'F05_3B_CREDENTIAL_DELETE_FORBIDDEN'; END IF;
 IF ROW(NEW.credential_id,NEW.secret_sha256,NEW.issue_event_key,
        NEW.issued_by_system_admin_id,NEW.issued_at)
     IS DISTINCT FROM ROW(OLD.credential_id,OLD.secret_sha256,OLD.issue_event_key,
        OLD.issued_by_system_admin_id,OLD.issued_at)
 THEN RAISE EXCEPTION 'F05_3B_CREDENTIAL_SOURCE_IMMUTABLE'; END IF;
 IF OLD.revoked_at IS NOT NULL OR NEW.revoked_at IS NULL OR NEW.version<>OLD.version+1
 THEN RAISE EXCEPTION 'F05_3B_CREDENTIAL_REVOCATION_IRREVERSIBLE'; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER f05_3b_credential_seal BEFORE UPDATE OR DELETE ON public.f05_3b_sync_credentials
FOR EACH ROW EXECUTE FUNCTION public.f05_3b_credential_guard();


-- Transport-level invocation audit: even invalid API keys and rejected requests are
-- counted without storing their values, VIN, caller IP or submitted payload.
CREATE TABLE public.f05_3b_api_call_logs (
 call_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 action TEXT NOT NULL CHECK(action IN ('upsert','offline','current','unknown')),
 method TEXT NOT NULL CHECK(method IN ('GET','POST','OTHER')),
 http_status INTEGER NOT NULL CHECK(http_status BETWEEN 200 AND 599),
 actor_kind TEXT NOT NULL CHECK(actor_kind IN ('INTEGRATION','SYSTEM')),
 submitted_count INTEGER NOT NULL DEFAULT 0 CHECK(submitted_count BETWEEN 0 AND 50),
 returned_count INTEGER NOT NULL DEFAULT 0 CHECK(returned_count BETWEEN 0 AND 50),
 processed_count INTEGER NOT NULL DEFAULT 0 CHECK(processed_count BETWEEN 0 AND 50),
 result_code TEXT NOT NULL CHECK(length(result_code) BETWEEN 3 AND 120),
 happened_at TIMESTAMPTZ NOT NULL DEFAULT transaction_timestamp()
);
CREATE INDEX f05_3b_api_call_time ON public.f05_3b_api_call_logs(action,happened_at);
CREATE TRIGGER f05_3b_transport_audit_immutable BEFORE UPDATE OR DELETE ON public.f05_3b_api_call_logs
FOR EACH ROW EXECUTE FUNCTION public.f05_3b_immutable_audit();
