CREATE INDEX f05_3b_receipt_source ON public.f05_3b_sync_receipts(car_code,happened_at);

CREATE FUNCTION public.f05_3b_lineage_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF TG_OP='DELETE' THEN RAISE EXCEPTION 'F05_3B_LINEAGE_DELETE_FORBIDDEN'; END IF;
 IF ROW(NEW.lineage_id,NEW.source_platform,NEW.car_code,NEW.vehicle_id,
        NEW.brand_id,NEW.series_id,NEW.model_id,NEW.model_year,NEW.first_seen_at)
    IS DISTINCT FROM
    ROW(OLD.lineage_id,OLD.source_platform,OLD.car_code,OLD.vehicle_id,
        OLD.brand_id,OLD.series_id,OLD.model_id,OLD.model_year,OLD.first_seen_at)
 THEN RAISE EXCEPTION 'F05_3B_LINEAGE_IDENTITY_IMMUTABLE'; END IF;
 IF NEW.version<>OLD.version+1 OR NEW.current_cycle_id=OLD.current_cycle_id
 THEN RAISE EXCEPTION 'F05_3B_LINEAGE_CYCLE_CAS_REQUIRED'; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER f05_3b_lineage_seal BEFORE UPDATE OR DELETE ON public.f05_3b_sync_lineages
FOR EACH ROW EXECUTE FUNCTION public.f05_3b_lineage_guard();

