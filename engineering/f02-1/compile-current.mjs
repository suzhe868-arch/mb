const key=(...parts)=>'f02_'+createHash('sha256').update(parts.join(':')).digest('hex').slice(0,20);
const sqlString=v=>"'"+v.replace(/'/g,"''")+"'";
const statementCheck=(t,c,expr)=>'ALTER TABLE '+quote(t)+' ADD CONSTRAINT '+quote(key(t,c,expr))+' CHECK ('+expr+');';
